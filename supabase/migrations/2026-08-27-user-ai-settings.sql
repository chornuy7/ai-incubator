-- MR-185: глобальный системный промпт — свой у каждого человека.
--
-- Было: один текст на всю платформу (ключ `ai-settings` в общем kv). Админ дописал себе
-- пару строк — они уехали ВСЕМ: и субам, и другим владельцам, и во все их запуски.
-- Это тот же корень, что и у карточек промптов: текст не был ничьим.
--
-- Владелец 27.08: «поменял глобальный промпт под администратором — остаётся только у меня,
-- не переходит ни на другой аккаунт, ни на мои аккаунты. На тестовом модераторе — только
-- у него».
--
-- Строка на человека, а не JSON в одной ячейке: настройка адресная, её читают по владельцу.
create table if not exists user_ai_settings (
  user_id       text primary key,
  -- Пустая строка = своего нет. Тогда подставится общий текст из старого kv (см. код):
  -- иначе в день выката у всех разом пропал бы уже настроенный промпт.
  global_prompt text not null default '',
  updated_at    timestamptz not null default now()
);

-- Доступ только у бэкенда (сервисный ключ обходит RLS). Публичной политики нет намеренно.
alter table user_ai_settings enable row level security;

comment on table user_ai_settings is 'MR-185: персональные ИИ-настройки. Глобальный системный промпт принадлежит человеку: правка одного не доезжает до других.';
comment on column user_ai_settings.global_prompt is 'Пусто — своего промпта нет, подставляется прежний общий текст. Первое сохранение заводит личный.';
