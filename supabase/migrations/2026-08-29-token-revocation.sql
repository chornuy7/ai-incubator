-- MR-203: гашение прежних токенов при выходе.
--
-- Токен сессии — stateless HMAC со сроком в неделю, а серверный выход его никак не
-- отзывал. Любая копия строки токена (застряла в хранилище браузера, попала в бэкап
-- профиля, снята с чужого экрана) оставалась рабочим ключом к аккаунту ещё до семи суток
-- ПОСЛЕ выхода. Чистка localStorage закрывала только тот браузер, где нажали «Выйти».
--
-- Отметка ниже — момент последнего выхода. Токен, выданный раньше неё, больше не
-- принимается (server/lib/tokenRevocation.js). Одна колонка вместо таблицы сессий: токен
-- остаётся stateless, а отзыв стоит ровно одну отметку времени.
--
-- NULL = человек ни разу не выходил после этой правки; все его текущие токены живут.
alter table profiles add column if not exists tokens_valid_from timestamptz;

comment on column profiles.tokens_valid_from is
  'MR-203: токены, выданные раньше этого момента, не принимаются (гасятся выходом).';
