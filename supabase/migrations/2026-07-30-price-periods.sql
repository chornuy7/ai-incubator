-- §11.2: периоды подписки со скидками — генерируемым списком, а не «месяц/год» в коде.
--
-- Со звонка 29.07: «сделай генерируемый список, чтобы можно было плюсик нажать и
-- добавить ещё что-то, и сделай период селектом — от недели до четырёх, от месяца до
-- шести, от года до пяти. Чтобы к этому потом не возвращаться».
--
-- Колонка nullable: пока её нет или она пустая, приложение работает по-старому
-- (месяц + год со скидкой annual_discount), поэтому применять можно без простоя.
--
-- Как применить: Supabase → SQL Editor → выполнить этот файл.

alter table price_overrides
  add column if not exists periods jsonb;

comment on column price_overrides.periods is
  'Периоды подписки: [{unit:week|month|year, count:int, discount:0..0.9}]. NULL = дефолт (месяц 0% + год annual_discount).';
