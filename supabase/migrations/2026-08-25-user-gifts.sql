-- MR-189: подарочные токены выдаются ОДИН раз и это где-то записано.
--
-- Созвон 24.08: «подарочные — они один раз только добавляются, и всё, это единоразовое
-- добавление». При разборе выяснилось хуже: подарок вообще НЕ начислялся. Он считался в
-- стоимости набора (`subscriptionCost().giftTokens`), показывался на витрине и в кабинете
-- («+200 ⚡ в подарок»), но ни одна из трёх точек начисления его не выдавала — ни оплата
-- подписки, ни ежемесячный крон, ни покупка пакета. Человеку обещали и не давали.
--
-- Почему отдельная таблица, а не флаг на подписке. Подарок привязан к ПАРЕ «человек +
-- модуль» и должен пережить отключение модуля: убрал парсер, через месяц вернул — подарок
-- второй раз не полагается. Строки `user_subscriptions` при отключении модуля исчезают,
-- поэтому память о выданном подарке им доверить нельзя.
create table if not exists user_gifts (
  id bigserial primary key,
  user_id text not null,
  module_key text not null,
  -- Сколько ⚡ выдали. Храним факт, а не текущую цену: подарок могли поменять после выдачи,
  -- и «сколько получил человек» должно остаться тем, что было на момент выдачи.
  coins integer not null,
  credited_at timestamptz not null default now(),
  -- Один подарок на пару «человек + модуль». Повторную выдачу гасит ON CONFLICT —
  -- вернуть модуль в подписку и получить подарок снова нельзя.
  unique (user_id, module_key)
);

create index if not exists user_gifts_user_idx on user_gifts (user_id);

-- Доступ только у бэкенда (сервисный ключ обходит RLS). Публичной политики нет намеренно.
alter table user_gifts enable row level security;

comment on table user_gifts is 'MR-189: журнал выданных подарочных ⚡. Подарок даётся один раз за пару «пользователь + модуль» и не выдаётся повторно при возврате модуля в подписку.';
