-- MR-290, шаг 5: «все модули» — свойство подписки, а не строка в списке модулей.
--
-- В user_subscriptions лежат строки с module_key = '*'. Строка этой таблицы означает
-- «у владельца есть модуль X»; строка со звёздочкой означает «есть все модули, включая
-- те, которых ещё нет». Это не модуль — это свойство самой подписки, записанное в чужое
-- поле. Отсюда три следствия, каждое из которых уже мешает:
--
--   • на module_key нельзя поставить внешний ключ на справочник модулей: звёздочка не
--     модуль, и ключ отверг бы её вместе с реальной подпиской двух администраторов;
--   • три места в коде (balance.js, tokenCredit.js, subscriptionBilling.js) вынуждены
--     помнить про метку и пропускать её вручную — забудешь в четвёртом, и «всё включено»
--     посчитается как покупка одного модуля с именем «*»;
--   • «сколько модулей у человека» нельзя посчитать запросом: надо сначала знать про метку.
--
-- Признак переезжает в subscriptions.all_modules — туда, где он описывает подписку
-- целиком, рядом со сроком и днём списания. Слово выбрано не новое: ровно так же
-- называется поле у наборов (setups.all_modules) с тем же смыслом.
--
-- ⚠️ СТРОКИ СО ЗВЁЗДОЧКОЙ ЗДЕСЬ НЕ УДАЛЯЮТСЯ, и внешнего ключа на справочник модулей
-- пока нет. Причина та же, что у состава групп: миграции применяются ДО выката кода, и
-- в промежутке работает старый код, который состав подписки читает строками. Удали
-- звёздочку сейчас — и на эти несколько минут у двух администраторов подписка выглядит
-- пустой, то есть доступ к модулям пропадает. Новый код перестаёт писать звёздочку и
-- начинает писать флаг; оставшиеся строки уберёт и ключ поставит отдельная миграция
-- следующим релизом.

alter table subscriptions add column if not exists all_modules boolean not null default false;

comment on column subscriptions.all_modules is
  'Подписка покрывает ВСЕ модули, включая будущие (админский провижининг). Раньше это была строка user_subscriptions с module_key = ''*'' — модуля с таким ключом не существует, и внешний ключ на справочник поставить было нельзя.';

update subscriptions s
   set all_modules = true,
       updated_at = now()
 where not s.all_modules
   and exists (select 1 from user_subscriptions us
                where us.user_id = s.id and us.module_key = '*');

-- ─────────────────────────────────────────────────────────────
-- Состав подписки связывается с самой подпиской
-- ─────────────────────────────────────────────────────────────
-- Владелец строки состава связывается не с кошельком напрямую, а с ПОДПИСКОЙ: отношение
-- здесь «подписка → её модули», и без подписки строка состава бессмысленна. Отсюда
-- CASCADE: убрали подписку — ушёл и её состав, без отдельного прохода в коде.
--
-- Проверено на живой базе: у всех 49 строк состава подписка есть (9 владельцев — 9 строк
-- в subscriptions), сирот нет. Данные этот ключ не меняет, поэтому он идёт уже сейчас.
create index if not exists user_subscriptions_module_idx on user_subscriptions (module_key);

alter table user_subscriptions
  add constraint user_subscriptions_subscription_fkey
    foreign key (user_id) references subscriptions(id) on delete cascade;

comment on table user_subscriptions is
  'Модули подписки, строка на модуль. Владелец — подписка (subscriptions.id), а не человек напрямую: у общей подписки владельца-человека нет вовсе. «Все модули» тут не хранится — это флаг самой подписки (subscriptions.all_modules).';
