-- MR-225: убрать мёртвый лимит у сотрудников, уже переведённых на свой кошелёк.
--
-- До MR-225 «лимит токенов» был потолком расхода ЧУЖИХ денег: сотрудник тратил баланс
-- владельца, пока не упирался в число. После MR-225 владелец ВЫДАЁТ токены — они уходят
-- с его баланса и становятся собственностью сотрудника.
--
-- Первая же выдача переключает сотрудника на свой кошелёк (`balance_mode = 'individual'`),
-- но старое число остаётся лежать в профиле. Работать оно уже не работает — `spendLimit`
-- не применяет потолок к владельцу собственного кошелька, — зато вводит в заблуждение:
-- приёмка 31.08 началась с вопроса «было 500, стало 200, куда делись 300?». Никуда: 500
-- были потолком чужих денег, а 200 — выданные свои.
--
-- ЧЕГО ЭТА МИГРАЦИЯ НАМЕРЕННО НЕ ДЕЛАЕТ.
--
-- Не трогает сотрудников на общем кошельке (`balance_mode` не 'individual'): у них лимит
-- ЖИВОЙ и прямо сейчас ограничивает расход. Снять его — открыть им весь баланс владельца;
-- обнулить и перевести на свой кошелёк — остановить им работу до ручной выдачи. Ни то ни
-- другое нельзя делать за владельца молча: это его деньги и его решение.
--
-- То есть перевод на новую модель остаётся ПОШТУЧНЫМ и осознанным — в момент, когда
-- владелец первый раз нажимает «Выдать». Миграция лишь убирает след, который уже ни на
-- что не влияет.
update public.profiles
   set token_limit = null
 where parent_id is not null
   and token_limit is not null
   and balance_mode = 'individual';
