-- MR-230: состав подписки — отдельной колонкой, а не строкой в тексте причины.
--
-- В журнале операция подписки пишется человеческим текстом: «Токены подписки (месяц):
-- Мейлинг, Нейрокомментинг, Нейрочаттинг и ещё 11». Длинный набор сворачивается, иначе
-- строка не читается. Но заказчик 31.08: «щоб не писало "и ещё 11", а я міг натиснути і
-- там покажеться фул список» — а разворачивать нечего: одиннадцати модулей в строке нет,
-- они потеряны при записи.
--
-- Достать их обратно разбором текста нельзя: названия модулей сами содержат запятые и
-- тире («AIR — AI Rating»), и любой разделитель когда-нибудь попадёт внутрь названия.
-- Поэтому состав фиксируем В МОМЕНТ ЗАПИСИ — как уже сделано с `currency`, `kind` и
-- `actor_id`: чем операция является, решает тот, кто её пишет, а не тот, кто читает.
--
-- Колонка необязательная: у строк, записанных до этой миграции, состава нет, и интерфейс
-- показывает их прежним свёрнутым текстом без разворота.
alter table wallet_log add column if not exists modules text[];
