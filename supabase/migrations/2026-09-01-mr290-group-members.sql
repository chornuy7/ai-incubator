-- MR-290, шаг 3: состав группы аккаунтов — строками, а не JSON-массивом.
--
-- `account_groups.account_ids` — jsonb-массив идентификаторов. На группы выдаются права
-- в ролях (isAccountAllowedViaGroups в server/accountGroups.js), то есть КОНТРОЛЬ ДОСТУПА
-- опирается на массив, у которого нет ни одной ссылки. База не знает, что внутри лежат
-- аккаунты, и не может помешать оставить в группе удалённый: он просто перестаёт что-либо
-- значить, молча и без следа. Ровно это уже случилось у соседей — в profiles.account_ids
-- и profiles.account_group_ids есть по одной ссылке на несуществующий объект.
--
-- Здесь состав переезжает в таблицу связи с двумя внешними ключами. Что это даёт:
--   • аккаунт, которого нет, в группу не положить — база откажет;
--   • удалили аккаунт — он исчезает из всех групп сам, без обхода JSON;
--   • «в каких группах этот аккаунт» становится обычным запросом с индексом, а не
--     разбором каждого массива в памяти (groupsByAccount сегодня делает именно это);
--   • пару «группа + аккаунт» нельзя завести дважды — за этим следит первичный ключ.
--
-- ⚠️ КОЛОНКА account_ids ЗДЕСЬ НЕ УДАЛЯЕТСЯ, хотя данные из неё переехали.
-- Миграции у нас применяются ДО выката кода (deploy.yml), поэтому между накаткой и
-- приездом нового кода живёт старый — а он читает именно колонку. Снимем её отдельной
-- миграцией следующим релизом, когда читателей не останется. До тех пор колонка лежит
-- мёртвым грузом и никем не пишется.

create table if not exists account_group_members (
  group_id   text not null references account_groups(id) on delete cascade,
  account_id text not null references accounts_meta(id)  on delete cascade,
  -- Порядок, в котором аккаунты показываются в группе. В JSON-массиве он был неявным
  -- свойством порядка элементов; в таблице строки неупорядочены, и без этой колонки
  -- состав группы каждый раз перемешивался бы.
  position   integer not null default 0,
  primary key (group_id, account_id)
);

create index if not exists account_group_members_account_idx on account_group_members (account_id);

comment on table account_group_members is
  'Состав группы аккаунтов. Переехал из jsonb-массива account_groups.account_ids (MR-290): на группы выдаются права, а массив не давал базе проверить, что аккаунт вообще существует.';

-- Перенос. `with ordinality` сохраняет порядок элементов массива — он же становится
-- position. Фильтра «только существующие аккаунты» здесь НЕТ намеренно: на 01.09 в
-- составе групп сирот нет (проверено), а если они появятся к моменту накатки — миграция
-- упадёт на внешнем ключе, и это правильно. Молча выбросить строку из состава группы
-- значит молча отобрать у кого-то доступ; такое должно останавливать выкат, а не
-- проходить незамеченным.
insert into account_group_members (group_id, account_id, position)
select g.id, e.value, (e.ordinality - 1)::int
from account_groups g,
     lateral jsonb_array_elements_text(g.account_ids) with ordinality as e(value, ordinality)
on conflict (group_id, account_id) do nothing;

comment on column account_groups.account_ids is
  'УСТАРЕЛО (MR-290): состав группы живёт в account_group_members. Колонка снимается следующим релизом — она ещё нужна коду, который на момент накатки миграции работает на сервере.';
