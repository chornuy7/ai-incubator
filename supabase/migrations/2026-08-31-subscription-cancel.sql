-- MR-228: отмена подписки.
--
-- Заказчик 30.08: «У тебя должно быть написано, какая подписка оплачена, до какого числа,
-- что в неё входит, и кнопка отмены. Возвратов нет».
--
-- Отмена НЕ отбирает доступ: человек заплатил за период и дорабатывает его до конца.
-- Она отменяет СЛЕДУЮЩЕЕ списание — и вместе с ним следующее начисление токенов, иначе
-- платформа выдавала бы топливо за месяц, который никто не оплатил.
--
-- Отдельная колонка, а не удаление подписки: удалив строку, мы потеряли бы и дату конца
-- оплаченного периода, и состав — то есть ровно то, что до этой даты должно работать.
alter table subscriptions add column if not exists canceled_at timestamptz;
