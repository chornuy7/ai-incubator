-- Подписки РЕЛЯЦИОННО: состав набора — строками, а не JSON-массивом.
--
-- Созвон 19.08, слова заказчика: «должна быть таблица, которая так и называется
-- user_subscription, где ты связываешь user_id и модуль, и должен быть написан due day —
-- когда истекает подписка… она просто пишет, что она есть. Это огромная дырка в
-- архитектуре». И отдельно, как постоянное правило: «никакого джейсона в базе данных».
--
-- Сейчас состав лежит в subscriptions.modules, причём РАЗНЫМИ типами: строка "all" у
-- админского провижининга и массив у клиентов. Одна колонка — две формы.
--
-- ПЕРЕНОСИМ ТОЛЬКО ХРАНЕНИЕ. Поведение уже правильное и менять его нельзя (контракт):
--   1. Одна дата на всю подписку. Строка на модуль — способ хранения, а НЕ помодульные
--      сроки: во всех строках пользователя дата одна и та же. Поэтому billing_day и
--      last_credit_month остаются на subscriptions (свойство подписки, не модуля) —
--      скопировать их в каждую строку значило бы завести помодульное начисление.
--   2. Состав объединяет сервер: список от клиента — «что выбрано», а не «что оставить».
--   3. Читаем ПОЛНЫЙ состав, включая истёкший: иначе просрочка выглядит как «ничего не
--      куплено» и продлевать в кабинете нечего.
create table if not exists user_subscriptions (
  id bigserial primary key,
  -- id профиля-владельца; 'workspace' — общий набор пространства (scope='workspace').
  user_id text not null,
  module_key text not null,
  started_at timestamptz not null default now(),
  -- Due day. Одна дата на всю подписку: при продлении обновляется у ВСЕХ строк
  -- пользователя, при докупке новая строка получает дату действующей подписки.
  -- null — срок не задан (админский провижининг: доступ без окончания).
  expires_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  -- Один модуль у пользователя — одна строка. Повторную оплату гасит ON CONFLICT,
  -- поэтому «оплатить уже оплаченное» не может задвоить запись.
  unique (user_id, module_key)
);

create index if not exists user_subscriptions_user_idx on user_subscriptions(user_id);
create index if not exists user_subscriptions_due_idx on user_subscriptions(expires_at);

-- Доступ только у бэкенда: он ходит сервисным ключом и RLS не касается. Публичной
-- политики нет намеренно — клиентским ключом состав чужих подписок не прочитать.
alter table user_subscriptions enable row level security;
