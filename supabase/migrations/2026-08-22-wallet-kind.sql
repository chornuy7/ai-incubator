-- §3.2 (MR-22): «Подарочные токены из подписки не учитывать как отдельный доход:
-- доходом является покупка плана. Покупку дополнительных токенов учитывать как
-- отдельную денежную операцию.»
--
-- До этого в доход шло ЛЮБОЕ положительное начисление ⚡: и купленные токены, и подарок
-- за подписку, и месячная выдача, и ручное начисление админом. Подписка за $20 попадала
-- в доход дважды — как оплата плана и как 200 выданных ⚡ по курсу.
--
-- kind фиксирует природу операции в момент записи: 'purchase' — куплено за деньги,
-- 'grant' — выдано (подарок, месячные токены, ручное начисление). У старых строк kind
-- пустой — отчёт разбирает их по тексту причины.
alter table wallet_log add column if not exists kind text;
create index if not exists wallet_log_kind_idx on wallet_log(kind);
