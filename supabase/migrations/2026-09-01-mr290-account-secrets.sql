-- MR-290, шаг 7: облачный пароль аккаунта — отдельной колонкой и в шифрованном виде.
--
-- В `accounts_meta.data.twoFA` открытым текстом лежит ОБЛАЧНЫЙ ПАРОЛЬ (2FA)
-- Telegram-аккаунта — у 47 аккаунтов из 63. Его собирает импорт из password.txt и
-- json-описаний рядом с сессией (accountScan.js:21 — ключи password, cloud_password,
-- two_factor_password), и хранится он не зря: без пароля аккаунт нельзя реавторизовать,
-- когда сессия отвалится, а взять его потом неоткуда.
--
-- Значит, удалить нельзя — надо закрыть. Здесь делается половина дела, доступная схеме:
-- пароль переезжает из общей jsonb-свалки в ОТДЕЛЬНУЮ колонку. Это не косметика:
--
--   • колонку видно в схеме, по ней можно искать и на неё можно выдать (или не выдать)
--     права — на ключ внутри jsonb ни того, ни другого не сделать;
--   • `select data from accounts_meta` перестаёт отдавать пароли заодно со всем
--     остальным, а таких запросов в коде хватает (loadAllMeta читает именно `data`);
--   • видно, что колонка секретная: имя говорит само за себя, а комментарий ниже
--     останется в схеме навсегда.
--
-- Вторая половина — само шифрование — живёт в приложении (server/lib/secretBox.js), а не
-- в базе, и это осознанно. В базе есть и pgcrypto, и Supabase Vault, но Vault хранит ключ
-- В ТОЙ ЖЕ БАЗЕ и отдаёт расшифровку представлением vault.decrypted_secrets, на которое у
-- service_role есть SELECT (проверено на боевой). То есть доступ, которым злоумышленник
-- прочитал бы пароль, даёт ему и ключ. Шифруя в приложении, мы держим ключ там, куда
-- доступ к базе не дотягивается, а в базу отправляем только шифротекст.
--
-- ⚠️ ДАННЫЕ ЭТА МИГРАЦИЯ НЕ ПЕРЕНОСИТ. Перенос требует ключа, а ключа в SQL нет и быть не
-- должно. Его делает `node server/scripts/encrypt-secrets.mjs` после выката кода: он
-- шифрует, ЧИТАЕТ ОБРАТНО И СВЕРЯЕТ, и только потом убирает открытый текст из jsonb.
-- До запуска скрипта работают оба пути — код читает колонку, а если её нет, старый ключ
-- в data.

alter table accounts_meta add column if not exists two_fa_enc text;

comment on column accounts_meta.two_fa_enc is
  'СЕКРЕТ. Облачный пароль (2FA) Telegram-аккаунта в шифрованном виде (конверт enc.v1.<keyId>.<iv>.<tag>.<ct>, AES-256-GCM). Ключ — SECRETS_KEY в окружении приложения, в базе его нет. Наружу не отдаётся никогда: API показывает только признак has2fa.';

-- Индекс намеренно НЕ заводим: по секрету не ищут и не сортируют, а индекс — это ещё одна
-- копия значения, которую тоже пришлось бы защищать.
