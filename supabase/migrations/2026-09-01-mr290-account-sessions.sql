-- MR-290, шаг 8: строки сессий Telegram — в базу и в шифрованном виде.
--
-- Сессия лежала файлом `server/data/sessions/<accountId>.session`, внутри — строка
-- StringSession открытым текстом (tgAuth.js: fs.writeFile(..., 'utf8')). Это САМЫЙ
-- сильный секрет системы: сессия — уже пройденная авторизация, ей не нужен ни телефон,
-- ни код, ни облачный пароль. Забрал каталог — забрал все аккаунты.
--
-- Два изъяна разом, и оба чинятся одним переездом:
--
--   1. Открытый текст. Копия каталога, бэкап сервера, доступ по SSH — и аккаунты чужие.
--      Шифруем тем же механизмом, что и облачные пароли (server/lib/secretBox.js): ключ
--      в окружении, в базе его нет.
--   2. Файл как хранилище. Правило владельца с созвона 24.08 — «другого способа хранения
--      быть не должно, ни файлов, ни SQLite». Пока сессии на диске, второй экземпляр
--      сервера видит другой набор аккаунтов, а переезд на другую машину означает ручное
--      копирование секретов.
--
-- ⚠️ ДАННЫЕ ЭТА МИГРАЦИЯ НЕ ПЕРЕНОСИТ — перенос требует ключа, а ключу в SQL не место.
-- Его делает `node server/scripts/sessions-to-db.mjs`: шифрует, читает обратно, сверяет,
-- и только потом предлагает убрать файлы. До переноса код читает базу, а если там пусто —
-- файл, поэтому окно выката ничего не ломает.

create table if not exists account_sessions (
  -- Владелец — аккаунт. CASCADE: удалили аккаунт — ушла и сессия, иначе на диске (а
  -- теперь в базе) остаётся живой доступ к аккаунту, которого «уже нет».
  account_id  text primary key references accounts_meta(id) on delete cascade,
  session_enc text not null,
  updated_at  timestamptz not null default now()
);

comment on table account_sessions is
  'СЕКРЕТ. Строки сессий Telegram (StringSession) в шифрованном виде. Переехали из файлов server/data/sessions (MR-290): лежали открытым текстом, а сессия — это готовый доступ к аккаунту без пароля и кода.';
comment on column account_sessions.session_enc is
  'Конверт enc.v1.<keyId>.<iv>.<tag>.<ct>, AES-256-GCM. Ключ — SECRETS_KEY в окружении приложения; в базе его нет и быть не должно.';

-- Индекс не нужен: обращение всегда по первичному ключу (одна сессия на аккаунт).
