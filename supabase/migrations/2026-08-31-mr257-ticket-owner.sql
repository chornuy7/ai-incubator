-- MR-257: адресат обращения — владелец пространства.
--
-- Раньше все обращения шли платформенной поддержке: сотрудник не мог написать СВОЕМУ
-- администратору, а поддержка отправляла его обратно к нему же. Заказчик 30.08:
-- «в поддержке тебе скажут: свяжитесь с администратором. А нахера мне этот круг?»
--
-- Пусто (NULL) — обращение к нам, как было. Заполнено — к владельцу пространства.
alter table public.tickets
  add column if not exists to_owner_id text;

-- Владелец открывает свой список часто (запросы сотрудников), выборка идёт по этому полю.
create index if not exists tickets_to_owner_id_idx on public.tickets (to_owner_id);
