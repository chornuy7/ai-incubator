-- Шаблоны настроек модулей переезжают из файлов в общую базу.
--
-- Находка 26.08: `taskStore` хранил шаблоны в `server/data/modules/<модуль>/presets.json`,
-- ветки Supabase там не было вовсе. Из этого следовало три вещи сразу:
--   • на локальной копии и на сервере наборы шаблонов разные — человек видит одно, а на
--     проде лежит другое (именно так и разошлись скриншоты владельца);
--   • второй инстанс платформы развёл бы шаблоны окончательно: у каждого свой файл;
--   • это прямое нарушение правила «никаких локальных хранилищ, только общая база».
--
-- `settings` держим как jsonb ОСОЗНАННО. Правило «состав — строками, а не JSON» касается
-- перечислений (модули подписки, промпты по карточкам): их читают, фильтруют и считают.
-- Шаблон же — снимок настроек ОДНОГО запуска: три десятка разнородных полей, свой набор
-- у каждого модуля, и смысл он имеет только целиком. Раскладывать его по строкам значило
-- бы завести таблицу «ключ-значение» и потерять и типы, и целостность снимка.
create table if not exists module_presets (
  id          text primary key,
  module_key  text not null,
  -- Владелец записи. NULL — легаси-шаблоны, заведённые до владельческой модели: их видит
  -- только админ (см. ownedForRequest), привязать их задним числом не к кому.
  user_id     text,
  name        text not null,
  color       text,
  -- Подпись «чей шаблон» — свободный текст из формы сохранения, НЕ права доступа.
  owner_label text,
  settings    jsonb not null default '{}'::jsonb,
  created_at  bigint not null
);

create index if not exists module_presets_module_idx on module_presets (module_key);
create index if not exists module_presets_owner_idx  on module_presets (user_id);

-- Доступ только у бэкенда (сервисный ключ обходит RLS). Публичной политики нет намеренно.
alter table module_presets enable row level security;

comment on table module_presets is 'Шаблоны настроек модулей. Переехали из файлов server/data/modules/*/presets.json (26.08): файловое хранение расходилось между инстансами и нарушало правило «только общая база».';
comment on column module_presets.settings is 'Снимок настроек запуска целиком. jsonb осознанно: набор полей свой у каждого модуля и осмыслен только целиком, по строкам его раскладывать нечего.';
comment on column module_presets.owner_label is 'Подпись «чей шаблон» из формы сохранения. Это текст для глаз, права доступа определяет user_id.';
