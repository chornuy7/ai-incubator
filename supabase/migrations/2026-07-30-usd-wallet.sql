-- §11.4: разделить деньги и токены.
--
-- Решение владельца 30.07: «баланс — это $, это основное; за них мы покупаем подписки
-- на модули и токены. Токены тратятся на действия в модулях».
--
-- До этого кошелёк был один — монеты (`coins`), которые списывались за действия, а $
-- показывался как их пересчёт по курсу пакетов. Теперь это ДВА независимых остатка:
--   • usd   — деньги: ими платят за подписку и покупают токены;
--   • coins — токены: расходуются модулями за действия (поле оставлено как есть,
--             чтобы не переписывать биллинг и не рисковать деньгами клиентов;
--             в интерфейсе оно называется «токены»).
--
-- Колонка добавляется с нулём: у существующих клиентов деньги на счёт ещё не заводили,
-- а их токены (coins) остаются нетронутыми — обнулять чужой баланс миграцией нельзя.
--
-- Как применить: Supabase → SQL Editor → выполнить этот файл.

alter table coin_balance
  add column if not exists usd numeric(14,2) not null default 0;

comment on column coin_balance.usd is
  '§11.4: денежный баланс ($). Им платят за подписку и покупают токены (coins). NULL быть не может — по умолчанию 0.';
