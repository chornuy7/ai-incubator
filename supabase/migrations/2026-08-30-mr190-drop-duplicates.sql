-- MR-190, часть 2: убрать вторые копии данных.
--
-- ⚠️ ЗАПУСКАТЬ ТОЛЬКО ПОСЛЕ ВЫКАТА КОДА этой же задачи. До выката состав наборов
-- читается из JSON-колонки, и снятие её оставит витрину подписок без модулей.

-- 1. Состав набора хранился дважды: JSON-колонка `bundles.modules` и строки
--    `bundle_modules`. Сверка 30.08 показала, что копии совпадают по всем трём наборам.
--    Источник правды — таблица связей: код читает состав из неё (server/bundles.js) и
--    пишет туда при создании набора. Пока источников два, они однажды разъедутся, и
--    клиент купит набор с одним составом, а получит другой.
alter table bundles drop column if exists modules;

-- 2. Вторая модель подписки. `subscription_modules` (47 строк) поддерживалась фоновой
--    синхронизацией и не читалась НИ ОДНИМ запросом в коде — проверено поиском по
--    server/ и src/. Настоящие данные живут в user_subscriptions (49 строк, MR-173).
drop table if exists subscription_modules;

-- 3. Заметка о таблице `users` (2 строки).
--
--    Люди живут в profiles (79 строк), но users всё ещё читается при входе по паролю
--    (server/users.js). Это НЕ дубль справочника: там лежит password_hash, которого в
--    profiles нет. Пока пароль не переехал, таблицу удалять нельзя — вход сломается.
--    Фиксируем назначение прямо в схеме, чтобы следующий аудит не предлагал её снести.
comment on table users is
  'Хранилище пароля для входа (password_hash). Профили людей — в profiles; здесь только учётные данные. Не удалять, пока вход по паролю читает эту таблицу.';
