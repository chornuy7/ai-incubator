-- CRM: «откуда пришёл лид» — лид помнит не только кампанию (campaign_id уже есть),
-- но и конкретную ЗАДАЧУ, которая его привела (task_id). Кампания может породить
-- несколько задач/прогонов, и оператору важно видеть источник по каждой отдельно
-- (правки заказчика 31.07: «видно, откуда пришёл — по id и по названию кампании»).
--
-- Аддитивно и nullable: старые лиды остаются валидны, приложение работает до и после.
-- Как применить: Supabase → SQL Editor → выполнить этот файл.

alter table leads add column if not exists task_id text;
create index if not exists leads_task_id_idx on leads(task_id);
