-- MR-185: тексты промптов — в базу и К ВЛАДЕЛЬЦУ.
--
-- Созвон 24.08: «при редактировании промтов применяется на всех пользователей свои
-- промты, а должно применяться только на 1 аккаунт». Причина: тексты лежали в памяти
-- браузера (`localStorage`, ключ `ai-incubator:prompts:<модуль>`) без имени владельца.
-- Отсюда сразу два симптома: правка одного человека доставалась всем, кто заходит с
-- этого компьютера, а со своего второго устройства он своих правок не видел вовсе.
--
-- Тот же корень у MR-176: применение шаблона не возвращало текст промпта.
--
-- ХРАНИМ СТРОКАМИ, а не массивом в одной ячейке — то же правило, что и у подписок
-- («никакого джейсона в базе»). Карточек у модуля немного, а строками видно, кто что
-- переписал, и правку одной карточки не нужно перезаписывать целым набором.
--
-- В таблице лежат ТОЛЬКО изменённые тексты. Заводские подставляет код: иначе на каждого
-- нового пользователя копировались бы шесть одинаковых строк, и смена заводского текста
-- не доехала бы ни до кого.
create table if not exists user_prompts (
  id bigserial primary key,
  -- id профиля-владельца. Промпт принадлежит человеку, а не браузеру.
  user_id text not null,
  module_key text not null,
  -- Номер карточки промпта в модуле (0-based) — он же promptIndex в настройках задачи.
  idx integer not null,
  body text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  -- Одна карточка у одного человека в одном модуле — одна строка. Повторное сохранение
  -- переписывает её через ON CONFLICT, а не плодит копии.
  unique (user_id, module_key, idx)
);

create index if not exists user_prompts_owner_idx on user_prompts (user_id, module_key);

-- Доступ только у бэкенда: он ходит сервисным ключом и RLS не касается. Публичной
-- политики нет намеренно — клиентским ключом чужие промпты не прочитать.
alter table user_prompts enable row level security;

comment on table user_prompts is 'MR-185: тексты промптов модулей, изменённые пользователем. Строка на карточку; заводские тексты здесь НЕ хранятся — их подставляет код. Владелец берётся из сессии, а не из параметров запроса.';
