-- MR-173, финальный шаг: JSON-колонки состава подписки больше нет.
--
-- Созвон 19.08: «никакого джейсона в базе данных». Состав живёт строками в
-- user_subscriptions (строка на пару «пользователь + модуль»), перенос выполнен и
-- сверен: 10 подписок → 33 строки, расхождений нет.
--
-- ВАЖНО про порядок: этот скрипт применяется ПОСЛЕ выката кода, который перестал читать
-- и писать эту колонку. Наоборот нельзя — работающая старая сборка пишет только сюда.
--
-- Отдельная причина убрать, а не оставить «на всякий случай»: у колонки стоит DEFAULT
-- 'all'. Код её уже не пишет, а Postgres подставляет значение сам — свежая подписка
-- выглядела бы как «все модули». Мина для любого, кто прочитает колонку по привычке.
alter table subscriptions drop column if exists modules;
