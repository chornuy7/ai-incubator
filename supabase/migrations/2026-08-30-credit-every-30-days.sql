-- Начисление токенов — через 30 дней после оплаты, а не по числу месяца.
--
-- Было две разные шкалы: деньги списывались каждые 30 суток (expires_at + 30 дней), а
-- токены приходили в то же ЧИСЛО месяца, что и покупка (subscriptions.billing_day).
-- Между февралём и мартом эти даты расходятся. Владелец 30.08: «якщо я платив 14, то
-- нарахування і зняття коштів буде через 30 днів, а не 30 числа».
--
-- Теперь обе шкалы одинаковые и считаются от МОМЕНТА последнего начисления.
alter table subscriptions add column if not exists last_credit_at timestamptz;

comment on column subscriptions.last_credit_at is
  'Момент последнего начисления месячных токенов. Следующее — через 30 суток после него.';

-- Точку отсчёта для уже живущих подписок ставим «сейчас»: так никто не получит начисление
-- дважды на стыке правил. Максимум — первая порция после этой миграции придёт на несколько
-- дней позже привычного; деньги это не затрагивает, у них своя шкала.
update subscriptions set last_credit_at = now() where last_credit_at is null and expires_at is not null;
