-- Учёт рабочего времени операторов переезжает из файла в общую базу.
--
-- Находка 27.08 (MR-186): `server/workLog.js` писал только в server/data/worklog.json.
-- По этим записям считают отработанное время — то есть, если по ним платят, это деньги:
--   • файл лежит на одной машине: пропал диск — смены не подтвердить ничем;
--   • при втором инстансе человек отметился на одном сервере, а вышел через другой —
--     сессия останется незакрытой навсегда, а её половина просто не попадёт в отчёт;
--   • это прямое нарушение правила «никаких локальных хранилищ, только общая база».
--
-- Одна строка = одна сессия труда (вход→выход). Незакрытая сессия — `end_at is null`.
create table if not exists work_log (
  id       text primary key,
  user_id  text not null,
  -- Время в миллисекундах, как во всём сторе: сравнения идут с Date.now() и переводить
  -- туда-сюда на каждом чтении значило бы плодить ошибки на границах суток.
  start_at    bigint not null,
  -- NULL — сессия ещё открыта (человек на смене прямо сейчас).
  end_at      bigint,
  duration_ms bigint not null default 0
);

-- Выборка всегда идёт по человеку и по времени: «сегодня» и «за 7 дней».
create index if not exists work_log_user_idx  on work_log (user_id, start_at desc);
-- Открытую сессию ищут при каждом входе и выходе — отдельный частичный индекс.
create index if not exists work_log_open_idx  on work_log (user_id) where end_at is null;

-- Доступ только у бэкенда (сервисный ключ обходит RLS). Публичной политики нет намеренно:
-- по этим строкам видно, кто когда работал.
alter table work_log enable row level security;

comment on table work_log is 'Сессии труда операторов (вход→выход). Переехали из server/data/worklog.json (27.08, MR-186): файл жил на одной машине, при втором инстансе смена не закрывалась.';
comment on column work_log.end_at is 'NULL — сессия открыта. Незакрытую в отчёте ограничивают потолком смены (OPEN_SESSION_CAP_MS): человек не работает 98 часов подряд, это просто не нажатый выход.';
