-- #5 (созвон 17.08): у таблицы bundles убрать колонку user_id.
--
-- ПОЧЕМУ. Наборы модулей ГЛОБАЛЬНЫЕ: их собирает админ, а видят все пользователи.
-- listBundles() не фильтрует по владельцу, rowToBundle владельца даже не читает —
-- значит user_id писался, но нигде не использовался (мёртвая колонка, наследие общего
-- owner-column паттерна, к наборам неприменимого). Кто создал набор — фиксирует audit_log
-- (событие bundle.create, поле initiator), так что информация не теряется.
--
-- БЕЗОПАСНОСТЬ. Код (server/bundles.js) больше не пишет user_id. RLS-политика на bundles
-- (2026-08-19-rls-policies.sql) — «активный профиль», НЕ owner-scoped, от колонки не зависит.
--
-- Как применить: Supabase → SQL Editor → выполнить.

alter table public.bundles drop column if exists user_id;
