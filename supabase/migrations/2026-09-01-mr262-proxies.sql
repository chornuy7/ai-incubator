-- MR-262: прокси переезжают в базу и связываются с аккаунтом КЛЮЧОМ, а не строкой.
--
-- Владелец 01.09: «мы же тысячу раз говорили, что прокси храним в БД, а не в аккаунте,
-- отдельно! С любого места добавление идёт в БД, и мы их забираем к аккаунту из БД, а в
-- таблице БД ссылка просто на строку, где прокси».
--
-- Как было до этой миграции:
--   · каталога прокси в базе не существовало вовсе — он жил файлом `data/proxies.json`;
--   · `accounts_meta.proxy` хранил ПОЛНУЮ строку подключения `socks5://user:pass@host:port`,
--     скопированную в каждый аккаунт.
--
-- Чем это плохо не в теории: смена пароля в каталоге не доходила до сорока аккаунтов —
-- у каждого своя копия строки; удаление прокси оставляло аккаунты со строкой, которой
-- больше нигде нет; «кем занят» и счётчик `usedBy` считались сравнением строк; а потеря
-- диска сервера означала потерю всех прокси — в резервной копии базы их не было.
--
-- Миграция аддитивная и идемпотентная: применяется до выката кода и после него, старый
-- код продолжает работать (колонка `proxy` остаётся и заполняется из каталога).

create table if not exists proxies (
  id            text primary key,            -- px_…
  label         text,
  kind          text not null default 'static',   -- static / mobile / farm
  scheme        text not null default 'socks5',   -- socks5 / http
  host          text not null,
  port          integer not null,
  username      text,
  password      text,
  country       text,
  -- Откуда взята страна: 'exit' — гео реального выходного IP, 'gateway' — гео шлюза,
  -- то есть «примерно». Без этого поля витрина показывала страну сервера как страну выхода.
  geo_source    text,
  rotate_url    text,                             -- ссылка смены IP от продавца
  status        text not null default 'unknown',  -- ok / bad / dead / unknown
  reason        text,                             -- почему статус такой
  note          text,
  -- Прокси — ресурс КЛИЕНТА (логин и пароль!), а каталог когда-то отдавался всем.
  -- Владелец пространства нужен, чтобы на чтении отдавать только своё.
  user_id       text,
  last_check_at bigint,
  created_at    bigint,
  updated_at    bigint
);

-- Уникальность прокси — host+port+логин+пароль (правило из MR-169, оно уже работает в коде).
-- Индекс переносит проверку на уровень базы: параллельный импорт из двух вкладок раньше
-- мог завести дубль, потому что «проверил → записал» делались не атомарно.
create unique index if not exists proxies_unique_endpoint
  on proxies (host, port, coalesce(username, ''), coalesce(password, ''));

-- Быстрый список «мои прокси»: чтение каталога всегда идёт с фильтром по владельцу.
create index if not exists proxies_user_idx on proxies (user_id);

-- Аккаунт ссылается на прокси КЛЮЧОМ. Внешнего ключа намеренно нет: прокси удаляют
-- (продавец отключил, срок кончился), и удаление не должно ронять аккаунт или молча
-- обнулять ссылку — пусть остаётся видно, на что он ссылался.
alter table accounts_meta add column if not exists proxy_id text;
create index if not exists accounts_meta_proxy_idx on accounts_meta (proxy_id);

-- Колонка `accounts_meta.proxy` НЕ удаляется. Она остаётся производной: строку подключения
-- собирает каталог, а здесь она лежит для читателей, которые ещё не переучены (и для
-- отката). Источник истины с этого момента — `proxy_id`.
