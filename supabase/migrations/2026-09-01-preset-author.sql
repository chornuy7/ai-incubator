-- MR-196: у шаблона появляется АВТОР — отдельно от пространства.
--
-- Заказчик 27.08: шаблоны общие для рабочего пространства (админ видит шаблон сотрудника
-- и наоборот) — это подтверждено правильным. Неправильным было то, что переименовать и
-- удалить чужой шаблон мог любой.
--
-- Причина в том, что «чей» у записи был один, и не тот: `user_id` хранит ПРОСТРАНСТВО, а у
-- администратора с его сотрудником оно совпадает. Проверка владения честно пропускала
-- обоих, потому что для неё это один и тот же владелец.
--
-- Колонка необязательная: у шаблонов, заведённых раньше, автора нет и восстановить его
-- нечем. Такие записи достаются хозяину пространства — он либо их и создал, либо за них
-- отвечает. Проставлять автором `user_id` задним числом нельзя: это назначило бы автором
-- владельца пространства даже там, где шаблон завёл сотрудник, и отобрало бы у сотрудника
-- его собственную заготовку.
alter table module_presets add column if not exists author_id text;
