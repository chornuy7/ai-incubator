-- Ежемесячное продление подписки: отметка «за какой месяц уже списали».
--
-- Решение владельца 28.08: «робимо списання кожного місяця, якщо річна підписка то просто
-- нараховуємо токени. Якщо балансу не вистачає тоді закриваємо доступ».
--
-- До этого денег после покупки не снимали вообще: человек платил за выбранный период
-- вперёд, срок заканчивался — доступ просто закрывался. Автопродления не было ни для
-- месячной подписки, ни для какой другой.
--
-- Колонка нужна именно ОТДЕЛЬНАЯ, а не «догадаемся по expires_at». Списание и сдвиг срока —
-- две записи, и между ними процесс может умереть. Если полагаться только на срок, после
-- такого сбоя следующий тик спишет деньги второй раз за тот же месяц. Отметка ставится
-- вместе со сдвигом срока и делает продление идемпотентным: повтор в том же месяце —
-- ничего не делает.
--
-- Формат тот же, что у last_credit_month: 'YYYY-MM' по UTC.
alter table subscriptions add column if not exists last_charge_month text;

comment on column subscriptions.last_charge_month is 'За какой месяц уже списали деньги за продление (YYYY-MM, UTC). Защита от повторного списания, если процесс умер между списанием и сдвигом срока.';
