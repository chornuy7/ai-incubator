/**
 * Тарифы для лендинга (B1). Лимиты аккаунтов ДОЛЖНЫ совпадать с `PLANS`
 * в `server/balance.js`: цифра на лендинге и лимит в системе — одно и то же
 * обещание, и расхождение означает, что клиент заплатил за одно, а получил другое.
 *
 * Цены здесь намеренно НЕ указаны: прайсы заказчик разбивает отдельно (SPEC §5.4),
 * и выдуманная сумма на публичной странице хуже её отсутствия.
 */
export interface PlanCard {
  id: string
  name: string
  accountLimit: number
  featured?: boolean
  perks: string[]
  /**
   * Цена за месяц. `null` — цена ещё не утверждена, и на лендинге вместо неё
   * показывается «по запросу»: выдуманная сумма на публичной странице хуже
   * её отсутствия. Ставите число — оно сразу появляется в карточке.
   */
  pricePerMonth?: number | null
  /** Валюта для показа. Меняется в одном месте вместе с ценами. */
  currency?: string
}

