/**
 * Раскладка карточек в ДВЕ КОЛОНКИ, когда карточек два размера: x1 (обычная) и
 * x2 (с блоком ошибки/проблемы) — ровно две x1 плюс зазор между ними.
 *
 * Зачем не обычный grid с авто-размещением: строка тянется по самой высокой
 * карточке, поэтому рядом с x2 у соседней x1 остаётся дыра, а вертикальные
 * отступы между блоками получаются разной величины — сетка выглядит рваной.
 * Дыру можно спрятать внутрь карточки (`items-stretch` + `h-full`), но тогда
 * раздувается каждая карточка, которой не повезло с соседом по строке.
 *
 * Правило: карточка идёт в ту колонку, которая сейчас КОРОЧЕ. Тогда она встаёт на
 * самую верхнюю свободную строку из двух возможных, а значит порядок чтения точно
 * совпадает с порядком списка: свежая задача всегда выше старой. Колонки при этом
 * расходятся максимум на две строки — пустое место остаётся только внизу.
 *
 * Почему не «первую половину списка налево, вторую направо»: тогда правая колонка
 * начинается с середины списка и отсортированный дашборд выглядит перемешанным
 * (ту раскладку уже пробовали и откатили 18.08).
 *
 * Почему не точная динамика по «перекосу колонок»: пробовали, она честно доводит
 * средний разрыв с 0.67 до 0.52 строки — и ломает порядок. На 3000 случайных
 * списков по 2..25 карточек: у жадности 0 нарушений порядка, у динамики — больше
 * трёх тысяч (задача поновее оказывается ниже, чем та, что старше). Четверть
 * строки того не стоит: по порядку задачу ищут глазами.
 *
 * Результат — координаты для CSS Grid. Высоту строки при этом НЕ задаём числом:
 * у сетки стоит `grid-auto-rows: 1fr`, и браузер сам делает все строки одинаковыми
 * по самому высокому содержимому, а карточка со `span 2` получает ровно две таких
 * строки плюс зазор. Отсюда и берётся равенство «x2 = две x1 + отступ»: никаких
 * магических пикселей, никакой обрезки текста, и любая карточка начинается и
 * заканчивается ровно на границе строки — сетка читается строками.
 */
export type PackInput<T> = { item: T; size: number }
/** Координаты в сетке: колонка 1|2, строка (с единицы) и высота в строках. */
export type Placement<T> = { item: T; col: 1 | 2; row: number; span: 1 | 2 }

export function packTwoColumns<T>(items: PackInput<T>[]): Placement<T>[] {
  const out: Placement<T>[] = []
  const h: [number, number] = [0, 0] // высота колонок в строках (x1 = 1, x2 = 2)
  for (const { item, size } of items) {
    const span = size >= 2 ? 2 : 1
    // При равной высоте — левая: порядок чтения идёт слева направо.
    const c = h[0] <= h[1] ? 0 : 1
    out.push({ item, col: (c + 1) as 1 | 2, row: h[c] + 1, span })
    h[c] += span
  }
  return out
}
