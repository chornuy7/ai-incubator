/**
 * Что из журнала кошелька относится к ПОДПИСКЕ.
 *
 * MR-230 (объединена с MR-199): в окне «История операций» на странице подписок должны быть
 * только подписки и купленные модули. Сейчас туда попадает вся история — рядом с покупкой
 * подписки висят строки вроде «parsing: 1 действ. −0.005 ⚡». Заказчик 27.08: «надо было
 * взять блок истории, который уже был внизу страницы подписок, и перенести его в модальное
 * окно, а сделали новый с нуля».
 *
 * ПОЧЕМУ ПО ТЕКСТУ ПРИЧИНЫ, А НЕ ПО ПОЛЮ. В журнале есть `kind`, но он занят другим смыслом —
 * покупка это или выдача (нужен для учёта дохода: «доходом является покупка плана»).
 * Переиспользовать его под «подписка / не подписка» значит сломать отчёт по деньгам.
 * Отдельной колонки нет, и заводить её ради фильтра в одном окне — дороже, чем польза.
 *
 * Фрагильность текстового разбора закрыта тестом `server/__tests__/walletKind.test.js`:
 * он берёт формулировки ИЗ КОДА СЕРВЕРА и проверяет, что классификатор их узнаёт. Поменяют
 * текст причины — упадёт тест, а не молча опустеет история у клиента.
 */

/** Начала причин, которые пишет сервер для операций по подписке. */
const ПОДПИСОЧНЫЕ = [
  'Подписка',              // покупка: «Подписка: на 1 мес. — Мейлинг, …»
  'Продление подписки',    // ежемесячное списание
  'Токены подписки',       // месячная порция токенов (первый месяц и последующие)
  'Подарочные токены',     // разовый подарок за модуль при покупке
]

/**
 * Операция относится к подписке?
 *
 * Пополнение счёта и покупка токенов сюда НЕ входят: это движение денег, а не подписка.
 * Им место в кошельке (Статистика → Кошелёк), где история осталась полной.
 */
export function isSubscriptionEntry(reason?: string | null): boolean {
  const t = String(reason || '').trim()
  return ПОДПИСОЧНЫЕ.some((p) => t.startsWith(p))
}

/** Для теста: тот же список, что используется в разборе. */
export const SUBSCRIPTION_REASON_PREFIXES = ПОДПИСОЧНЫЕ
