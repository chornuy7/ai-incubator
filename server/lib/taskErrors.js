/**
 * Что показать оператору, когда задача упала.
 *
 * ЗАЧЕМ. Верхние `catch` воркеров писали в лог задачи сырой текст исключения, и он же
 * попадал на дашборд как «Ошибка задачи». Владелец увидел там
 * «fromRow is not a function or its return value is not iterable» — фрагмент внутренней
 * поломки, по которому оператору нельзя ни понять, что случилось, ни что-либо сделать.
 * Хуже того, такая строка выглядит как претензия к нему: он запускал задачу, а ему в
 * ответ показали неисправность движка на чужом языке.
 *
 * РАЗДЕЛЕНИЕ ПРОСТОЕ И НЕ ЭВРИСТИЧЕСКОЕ.
 *
 *   Наши ошибки — это условия работы: «нет сессии», «прокси не отвечает», «не хватает
 *   монет». Их бросают явно, с готовой человеческой формулировкой, и её надо показать
 *   как есть: оператор по ней и чинит.
 *
 *   Встроенные типы ошибок JavaScript (TypeError, ReferenceError и остальные) условием
 *   работы не бывают НИКОГДА. Это всегда дефект кода. Их текст пишется в лог сервера —
 *   разработчику он нужен целиком, со стеком, — а оператору говорится, что сломалось у
 *   нас, а не у него.
 *
 * Проверка по `err.name`, а не по языку сообщения: язык — это совпадение, а тип ошибки
 * ставит сам движок.
 */

/** Типы, которые бросает сам JavaScript. Появление любого — дефект, а не ситуация. */
const ВНУТРЕННИЕ = new Set([
  'TypeError', 'ReferenceError', 'RangeError', 'SyntaxError', 'EvalError', 'URIError',
])

/**
 * Текст ошибки для лога ЗАДАЧИ (его видит оператор).
 *
 * @param {unknown} err
 * @param {string} [где] откуда упало — уходит в лог сервера, не оператору
 * @returns {string}
 */
export function taskErrorText(err, где = '') {
  if (err instanceof Error && ВНУТРЕННИЕ.has(err.name)) {
    // Полный стек — в лог сервера. Без него дефект придётся искать по одной строке.
    console.error(`[task] внутренняя ошибка${где ? ` (${где})` : ''}:`, err.stack || err)
    return 'Внутренняя ошибка платформы — задача остановлена. Это неисправность на нашей стороне, не в ваших настройках: она уже записана в журнал сервера. Запустите задачу заново.'
  }
  if (err instanceof Error && err.message) return err.message
  return 'Ошибка'
}
