/**
 * Совпадение ключевого слова с названием канала — для выдачи из своей базы (27.08).
 *
 * Почему не `includes`. Первая версия искала подстроку, и ключ «СТО» находил
 * «ре-СТО-раны»: в выдаче по массажу и разработчикам появился «Вкусный Чат — о еде,
 * ресторанах» (прогон владельца 27.08: «настройки поиска одни, а результат сумбурный»).
 *
 * Почему не строгая граница слова. Она режет словоформы: «массаж» перестаёт находить
 * «Массажист» и «Массажа» — а человек ищет именно их.
 *
 * Правило посередине: совпадение с НАЧАЛА слова, а для коротких ключей (три символа и
 * меньше) — строго целым словом. Короткий ключ почти всегда аббревиатура («СТО», «ИТ»),
 * и префикс пустил бы его в «стоматологию»; длинный — слово с окончаниями.
 */

/** Экранирование для вставки в регулярное выражение. */
const esc = (k) => String(k).replace(/[.*+?^${}()|[\]\\]/g, '\\$&')

/** Граница «не буква и не цифра» — работает и для кириллицы, и для латиницы. */
const NOT_WORD = '[^\\p{L}\\p{N}]'

/**
 * @param {string} keyword ключевое слово или фраза
 * @returns {RegExp} совпадение по началу слова (короткие ключи — целиком)
 */
export function keywordRegex(keyword) {
  const k = String(keyword || '').trim()
  if (!k) return /(?!)/ // пустой ключ не совпадает ни с чем
  const tail = k.length <= 3 ? `(${NOT_WORD}|$)` : ''
  return new RegExp(`(^|${NOT_WORD})${esc(k)}${tail}`, 'iu')
}

/**
 * Совпал ли текст (название + username) хотя бы с одним ключом.
 * @param {string} text @param {RegExp[]} regexps
 */
export function matchesAny(text, regexps) {
  const t = String(text || '')
  return regexps.some((re) => re.test(t))
}
