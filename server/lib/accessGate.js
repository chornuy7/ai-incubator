/**
 * Замок «доступ отключён» на весь /api.
 *
 * ПОЧЕМУ ЗДЕСЬ, А НЕ ТОЛЬКО В SUPABASE. На стороне БД RLS уже включён глухой стеной
 * (см. migrations/2026-07-31-rls.sql): у anon/authenticated нет ни одной policy, то есть
 * снаружи таблицы недоступны вообще. Но весь наш бэкенд ходит СЕРВИСНЫМ ключом, который
 * RLS обходит по определению — значит правило «нет доступа → нет данных» обязано жить и
 * в API. Иначе отключённый пользователь продолжал бы читать всё через наши эндпоинты.
 *
 * ЧТО ДЕЛАЕМ. Пользователь с `active = false` (профиль отключён) получает 403 на любой
 * /api-запрос, кроме узкого списка: посмотреть, кто он и почему закрыт, оплатить/продлить
 * и написать в поддержку. Всё остальное — как будто данных не существует.
 *
 * Монтируется СРАЗУ после sessionGuard: личность к этому моменту уже доверенная
 * (взята из подписанного токена, а не из заголовка клиента).
 */
import { getUser } from '../users.js'

/**
 * Что остаётся доступным отключённому пользователю.
 *
 * Смысл списка: человек должен увидеть СВОЁ состояние и иметь возможность его исправить —
 * иначе отключение выглядит как поломка сайта. Ничего чужого и никаких рабочих данных
 * (аккаунты, задачи, лиды, прокси, модули) сюда не входит.
 */
const ALLOWED_WHEN_DISABLED = [
  /^\/api\/health(\/|$|\?)/,
  /^\/api\/session(\/|$|\?)/,        // кто я, жива ли сессия
  /^\/api\/users\/(login|logout|register|me)(\/|$|\?)/,
  /^\/api\/me(\/|$|\?)/,             // свой профиль
  /^\/api\/profile(\/|$|\?)/,
  /^\/api\/subscription(\/|$|\?)/,   // что с подпиской и как её оплатить
  /^\/api\/billing(\/|$|\?)/,
  /^\/api\/pricing(\/|$|\?)/,
  /^\/api\/tickets(\/|$|\?)/,        // написать в поддержку («почему меня закрыли»)
]

function isAllowedWhenDisabled(req) {
  if (req.method === 'OPTIONS') return true
  const url = req.originalUrl || req.url
  return ALLOWED_WHEN_DISABLED.some((re) => re.test(url))
}

/** Express-middleware: `app.use('/api', accessGate)` сразу после sessionGuard. */
export async function accessGate(req, res, next) {
  try {
    const userId = req.header('x-user-id')
    if (!userId) return next() // гость/дев — этим занимается sessionGuard
    if (isAllowedWhenDisabled(req)) return next()

    const user = await getUser(userId)
    // Неизвестный пользователь — тоже закрыт: удалённый профиль не должен работать
    // по старому токену. Fail-closed: сомневаешься — не пускай.
    if (!user || user.active === false) {
      return res.status(403).json({
        ok: false,
        code: 'ACCESS_DISABLED',
        // Правка 21.08 (§5). В тексте стояло «или продлите подписку» — и человек шёл
        // платить, хотя закрыл его АДМИНИСТРАТОР, а подписка тут ни при чём (её срок
        // проверяет modulesAllow, и отказ там свой). Ложная подсказка стоила и денег,
        // и обращений в поддержку «оплатил, а не открылось». Говорим только то, что
        // правда: доступ выключен вручную, вернуть его может тот, кто выключил.
        error: 'Доступ к платформе отключён администратором.',
      })
    }
    next()
  } catch {
    // Сбой проверки не должен открывать дверь.
    res.status(503).json({ ok: false, error: 'Не удалось проверить доступ' })
  }
}
