/**
 * Человеческие тайминги: сколько времени у живого человека занимает НАБРАТЬ сообщение
 * и ПЕРЕКЛЮЧИТЬСЯ с одного занятия на другое.
 *
 * Зачем отдельный файл. Раньше эти числа стояли прямо в коде воркеров — «40 слов в
 * минуту», «пауза 1–5 секунд» — взятые на глаз, без источника и без разброса. Ровно об
 * этом вопрос владельца 21.08: «сколько печатает в среднем человек, взять минимум и
 * максимум, высчитать как рандом и вставить в задержку». Собрали в одном месте, с
 * происхождением каждого числа, чтобы их можно было обсуждать и менять осознанно.
 *
 * ОТКУДА ЧИСЛА (замеры, не ощущения):
 *
 * 1) Набор текста. Исследование Aalto University / Cambridge / ETH Zürich (2019) на
 *    37 000 участниках из 160 стран: средняя скорость набора на телефоне — 36.2 слова
 *    в минуту, у 75% участников ниже 44 слов/мин. Двумя большими пальцами — 38, одним
 *    пальцем — 29. Подростки быстрее сорокалетних примерно на 10 слов/мин.
 *    Отсюда рабочий диапазон 26–44: он покрывает и «одним пальцем», и уверенного
 *    печатающего, а середина совпадает со средним по выборке.
 *
 * 2) Переключение между занятиями. Здесь легко ошибиться на два порядка: широко
 *    известные «23 минуты» (Gloria Mark) — это время вернуться к ПРЕРВАННОЙ сложной
 *    работе, а не переключиться между однотипными делами. Нам нужна вторая величина —
 *    resumption lag: в замерах она порядка 25 секунд. Отсюда 10–45 секунд со средним
 *    около 25: столько человек тратит, закончив комментировать и переходя к переписке.
 *
 * Все функции чистые, `rnd` — параметр: тайминги проверяются тестами без бросков кубика.
 */

/**
 * Скорость набора, слов в минуту. Диапазон, а не одно число: одинаковая скорость у
 * пятидесяти аккаунтов — это ритм машины, ровно тот признак, по которому находят ферму.
 */
export const TYPING_WPM = { min: 26, max: 44 }

/**
 * «Задуматься перед первым словом», мс. Человек не начинает печатать в ту же миллисекунду,
 * когда дочитал.
 */
export const THINK_MS = { min: 700, max: 3000 }

/** Скорость чтения, знаков в секунду, и нижняя граница паузы на чтение. */
export const READ_CPS = 15
export const READ_MIN_MS = 3000

/**
 * Переключение между модулями, мс. Не «23 минуты» из популярных пересказов — это про
 * возвращение к прерванной сложной работе; здесь resumption lag однотипных занятий.
 */
export const SWITCH_MS = { min: 10_000, max: 45_000 }

/** Случайное целое в диапазоне включительно. @param {{min:number,max:number}} r */
export function pickInRange(r, rnd = Math.random) {
  const lo = Math.min(r.min, r.max)
  const hi = Math.max(r.min, r.max)
  return lo + Math.round(rnd() * (hi - lo))
}

/**
 * Сколько человек будет набирать это сообщение и сколько перед этим читал входящее.
 *
 * Возвращает и сами числа (`wpm`, `words`), а не только миллисекунды: их пишем в лог,
 * иначе «пауза 14 с» выглядит взятой с потолка — а именно на это и жаловались.
 *
 * @param {string} text что отправляем
 * @param {number} [incomingLen] длина входящего, которое «читаем» перед ответом
 * @param {() => number} [rnd]
 * @returns {{readMs:number, typeMs:number, thinkMs:number, totalMs:number, wpm:number, words:number}}
 */
export function typingPlan(text = '', incomingLen = 0, rnd = Math.random) {
  const words = String(text || '').trim().split(/\s+/).filter(Boolean).length
  const wpm = pickInRange(TYPING_WPM, rnd)
  const thinkMs = pickInRange(THINK_MS, rnd)
  const typeMs = thinkMs + Math.round((words / wpm) * 60_000)
  const readMs = Math.max(READ_MIN_MS, Math.round((Number(incomingLen) || 0) / READ_CPS * 1000))
  return { readMs, typeMs, thinkMs, totalMs: readMs + typeMs, wpm, words }
}

/** Пауза при переходе аккаунта из модуля в модуль. @param {() => number} [rnd] */
export function switchPause(rnd = Math.random) {
  return pickInRange(SWITCH_MS, rnd)
}

/** «14 с» / «2 мин 5 с» — короткая подпись длительности для логов и карточки аккаунта. */
export function fmtDelay(ms) {
  const s = Math.max(0, Math.round(Number(ms) || 0) / 1000)
  if (s < 60) return `${s < 10 ? s.toFixed(1).replace('.0', '') : Math.round(s)} с`
  const m = Math.floor(s / 60)
  const rest = Math.round(s % 60)
  return rest ? `${m} мин ${rest} с` : `${m} мин`
}

/**
 * Строка для лога: что именно система насчитала и почему столько.
 * «набирает 12 с: 34 слова со скоростью 38 сл/мин + 1.4 с на подумать».
 */
export function describeTyping(plan) {
  return `${fmtDelay(plan.typeMs)}: ${plan.words} сл. со скоростью ${plan.wpm} сл/мин + ${fmtDelay(plan.thinkMs)} на подумать`
}
