/**
 * MR-262: связь «аккаунт → прокси» ключом, а не копией строки подключения.
 *
 * Владелец 01.09: «мы же тысячу раз говорили, что прокси храним в БД, а не в аккаунте,
 * отдельно! С любого места добавление идёт в БД, и мы их забираем к аккаунту из БД, а в
 * таблице БД ссылка просто на строку, где прокси».
 *
 * Как было: `accounts_meta.proxy` хранил полную строку `socks5://user:pass@host:port`,
 * скопированную в каждый аккаунт. Смена пароля в каталоге до аккаунтов не доходила —
 * у каждого своя копия; удаление прокси оставляло аккаунт со строкой-призраком; «кем
 * занят» считалось сравнением строк.
 *
 * Как стало: в аккаунте лежит ТОЛЬКО `proxyId`. Строка подключения не хранится нигде —
 * она собирается из каталога на каждом чтении меты (`withProxyStrings`). Владелец 01.09:
 * «чтобы с таблицы accounts_meta тянулись прокси с proxies, а не сохранялись прям там».
 *
 * Читатели — воркеры, проверки, витрина — не переучивались: они по-прежнему видят поле
 * `proxy`, просто теперь оно всегда свежее, потому что берётся из каталога, а не из копии.
 */
import { toProxyUrl } from '../proxies.js'

/**
 * Что записать аккаунту при назначении прокси — ТОЛЬКО ссылка.
 *
 * Владелец 01.09: «чтобы с таблицы accounts_meta тянулись прокси с proxies, а не
 * сохранялись прям там». Строку не пишем вовсе: она производная и протухнет при первой же
 * смене пароля в каталоге. Читателям её отдаёт `withProxyStrings` на чтении меты.
 *
 * Снятие прокси чистит и ссылку, и остатки строки: иначе «без прокси» показывало бы
 * прежний адрес.
 *
 * @param {object|null} proxy запись каталога; `null` — снять прокси
 * @returns {{proxyId: string, proxy?: string}}
 */
export function proxyPatch(proxy) {
  if (!proxy) return { proxyId: '', proxy: '' }
  return { proxyId: proxy.id || '' }
}

/**
 * Найти в каталоге прокси по строке подключения — для переноса старых записей.
 *
 * Сравниваем по СОБРАННОЙ строке, а не по host+port: у одного хоста бывает несколько
 * записей с разными логинами, и по адресу их не различить.
 *
 * @param {object[]} каталог @param {string} url
 * @returns {object|null}
 */
export function findByUrl(каталог, url) {
  const нужная = String(url || '').trim()
  if (!нужная) return null
  return (каталог || []).find((p) => toProxyUrl(p) === нужная) || null
}
