/**
 * MR-262: связь «аккаунт → прокси» ключом, а не копией строки подключения.
 *
 * Владелец 01.09: «мы же тысячу раз говорили, что прокси храним в БД, а не в аккаунте,
 * отдельно! С любого места добавление идёт в БД, и мы их забираем к аккаунту из БД, а в
 * таблице БД ссылка просто на строку, где прокси».
 *
 * Как было: `accounts_meta.proxy` хранил полную строку `socks5://user:pass@host:port`,
 * скопированную в каждый аккаунт. Смена пароля в каталоге до аккаунтов не доходила —
 * у каждого своя копия; удаление прокси оставляло аккаунт со строкой-призраком; «кем
 * занят» считалось сравнением строк.
 *
 * Как стало: источник истины — `proxyId`. Строка `proxy` остаётся, но становится
 * ПРОИЗВОДНОЙ: её пересобирает каталог на каждом чтении меты. Поэтому все читатели —
 * воркеры, проверки, витрина — не переучивались и получают свежие данные сами.
 *
 * Почему строку не убрали совсем: её читают в полутора десятках мест, включая GramJS и
 * фоновые проверки. Одномоментная замена всех читателей — это отдельный риск ради формы
 * записи; ссылка уже решает задачу, а строка теперь всегда собрана из каталога.
 */
import { listProxies, toProxyUrl } from '../proxies.js'

/**
 * Подставить в мету свежую строку подключения по `proxyId`.
 *
 * @param {Record<string, object>} all мета всех аккаунтов (id → объект)
 * @returns {Promise<Record<string, object>>} она же, с пересобранными `proxy`
 */
export async function withProxyStrings(all) {
  const мета = all && typeof all === 'object' ? all : {}
  const ссылки = Object.values(мета).some((m) => m && m.proxyId)
  if (!ссылки) return мета // никто не переехал на ключи — каталог читать незачем

  let каталог = []
  try {
    каталог = await listProxies()
  } catch {
    return мета // каталог недоступен — отдаём как есть, старая строка лучше пустоты
  }
  const поКлючу = new Map(каталог.map((p) => [p.id, p]))

  const out = {}
  for (const [id, m] of Object.entries(мета)) {
    if (!m || !m.proxyId) { out[id] = m; continue }
    const p = поКлючу.get(m.proxyId)
    /*
     * Прокси удалили из каталога. Строку НЕ чистим: аккаунт продолжит работать на том, что
     * у него было, а «прокси исчез» — это разговор с человеком, а не молчаливый обрыв
     * связи посреди задачи. Признак `proxyGone` даёт витрине сказать об этом словами.
     */
    if (!p) { out[id] = { ...m, proxyGone: true }; continue }
    out[id] = { ...m, proxy: toProxyUrl(p) || m.proxy || '' }
  }
  return out
}

/**
 * Что записать аккаунту при назначении прокси.
 *
 * Пишем И ключ, И строку: ключ — источник истины, строка — то, что читают все остальные
 * (и то, что останется, если каталог однажды не ответит).
 *
 * @param {object|null} proxy запись каталога; `null` — снять прокси
 * @returns {{proxyId: string, proxy: string}}
 */
export function proxyPatch(proxy) {
  if (!proxy) return { proxyId: '', proxy: '' }
  return { proxyId: proxy.id || '', proxy: toProxyUrl(proxy) }
}

/**
 * Найти в каталоге прокси по строке подключения — для переноса старых записей.
 *
 * Сравниваем по СОБРАННОЙ строке, а не по host+port: у одного хоста бывает несколько
 * записей с разными логинами, и по адресу их не различить.
 *
 * @param {object[]} каталог @param {string} url
 * @returns {object|null}
 */
export function findByUrl(каталог, url) {
  const нужная = String(url || '').trim()
  if (!нужная) return null
  return (каталог || []).find((p) => toProxyUrl(p) === нужная) || null
}
