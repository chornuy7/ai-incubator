/**
 * MR-292: ЧТО именно с аккаунтом и что с этим делать.
 *
 * Владелец 01.09: «нам нужно определять, что с аккаунтом, и давать чёткое понятие».
 * До этого ограничение было одно на все случаи — статус `spamblock`, — хотя виды
 * различаются сроком, шансом снятия и тем, что вообще делать с аккаунтом.
 *
 * ВАЖНО про гео. В обиходе его называют «гео-спамблок», но Telegram такого не сообщает:
 * @SpamBot не говорит «у тебя ограничение из-за страны». Несовпадение страны аккаунта и
 * страны прокси — это НАША оценка риска, а не факт от платформы. Поэтому вид ограничения
 * и фактор риска здесь разведены: врать, будто Telegram назвал причину, нельзя.
 */
import { normalizeStatus, STATUS } from './accountStatus.js'

/** Виды ограничения — то, что сообщает сам Telegram. */
export const LIMIT = {
  NONE: 'none',
  TEMPORARY: 'temporary',   // ограничение со сроком: Telegram сказал, когда отпустит
  PERMANENT: 'permanent',   // спамблок без срока: даты снятия нет
  BANNED: 'banned',         // аккаунт удалён/заблокирован/заморожен платформой
  REAUTH: 'reauth',         // сессия протухла: аккаунт цел, нужен повторный вход
}

/*
 * Подпись говорит про ограничения СО СТОРОНЫ TELEGRAM, и «Ограничений нет» относится
 * только к ним: аккаунт может стоять на паузе или в карантине по нашему решению — это
 * наши правила, а не запрет платформы, и путать их нельзя.
 */
const ПОДПИСЬ = {
  [LIMIT.NONE]: 'Ограничений Telegram нет',
  [LIMIT.TEMPORARY]: 'Спамблок временный',
  [LIMIT.PERMANENT]: 'Спамблок без срока',
  [LIMIT.BANNED]: 'Заблокирован Telegram',
  [LIMIT.REAUTH]: 'Нужен повторный вход',
}

/** Флудвейт — тоже временное ограничение, но с другой причиной и другим советом. */
const ФЛУДВЕЙТ = {
  label: 'Флуд-контроль',
  what: 'Telegram притормозил аккаунт за частоту действий и назвал срок. Ничего делать не нужно —'
    + ' по истечении срока аккаунт вернётся в работу сам. Если повторяется, снизьте темп модуля.',
}

/**
 * Что делать — словами оператора, а не кодом.
 *
 * Отвечаем на единственный вопрос, который тут задают: работать этим аккаунтом или нет и
 * что предпринять. Без этого «Спамблок» на карточке остаётся диагнозом без назначения.
 */
const ЧТО_ДЕЛАТЬ = {
  [LIMIT.NONE]: 'Аккаунт в строю.',
  [LIMIT.TEMPORARY]: 'Подождать до конца срока — вернётся в работу сам. Нагружать до этого нельзя: действия под ограничением его продлевают.',
  [LIMIT.PERMANENT]: 'Срок Telegram не назвал. Помогает только апелляция («Снятие спамблока»); если не снимут за несколько попыток, аккаунт дешевле заменить, чем спасать.',
  [LIMIT.BANNED]: 'Решение платформы, входом не чинится. Восстановлению не подлежит — заменить.',
  [LIMIT.REAUTH]: 'Аккаунт цел, умерла сессия: войти повторно по номеру.',
}

/**
 * Вид ограничения по мете аккаунта.
 *
 * @param {{status?: string, statusUntil?: number|null, statusUntilSource?: string}} meta
 * @param {number} [now]
 * @returns {{kind: string, label: string, what: string, until: number|null}}
 */
export function limitKind(meta, now = Date.now()) {
  const s = normalizeStatus(meta?.status)
  const until = Number(meta?.statusUntil) || null

  if (s === STATUS.INVALID) return собрать(LIMIT.BANNED, null)
  if (s === STATUS.REAUTH) return собрать(LIMIT.REAUTH, null)
  /*
   * Флудвейт — единственный случай, где срок ВСЕГДА настоящий: его называет сам Telegram
   * числом секунд в ошибке FLOOD_WAIT_X, гадать не приходится.
   */
  if (s === STATUS.FLOODWAIT) return собрать(LIMIT.TEMPORARY, until && until > now ? until : null, ФЛУДВЕЙТ)
  if (s !== STATUS.SPAMBLOCK) return собрать(LIMIT.NONE, null)

  /*
   * Временный — только когда срок назвал САМ @SpamBot (MR-291). Дефолтные сутки, которые
   * подставляет наш код, сроком не являются: проверка 02.09 показала шесть аккаунтов из
   * шести всё ещё в блоке спустя пять дней после такого «срока». Выдавать догадку за
   * обещание Telegram — то же самое, что врать оператору.
   */
  const срокОтБота = meta?.statusUntilSource === 'spambot' && until && until > now
  return собрать(срокОтБота ? LIMIT.TEMPORARY : LIMIT.PERMANENT, срокОтБота ? until : null)
}

function собрать(kind, until, свои = null) {
  return { kind, label: свои?.label || ПОДПИСЬ[kind], what: свои?.what || ЧТО_ДЕЛАТЬ[kind], until }
}

/**
 * Фактор риска: страна аккаунта против страны прокси.
 *
 * Это НЕ вид ограничения и не диагноз от Telegram — наша оценка. Держим отдельно от
 * `limitKind`, чтобы на витрине не выглядело, будто платформа назвала причину.
 *
 * Смысл в том, что профиль, зарегистрированный под одну страну и работающий через IP
 * другой, для антиспама выглядит неестественно — это одна из частых причин ограничений
 * у новых аккаунтов.
 *
 * @param {{country?: string}} meta @param {{country?: string}|null} proxy
 * @returns {{mismatch: boolean, text: string}|null} null — сравнивать нечего
 */
export function geoRisk(meta, proxy) {
  const акк = String(meta?.country || '').trim().toLowerCase()
  const пркс = String(proxy?.country || '').trim().toLowerCase()
  if (!акк || !пркс) return null // без обеих стран вывод был бы гаданием
  if (акк === пркс) return { mismatch: false, text: `Гео совпадает: аккаунт и прокси — ${акк.toUpperCase()}` }
  return {
    mismatch: true,
    text: `Гео расходится: аккаунт ${акк.toUpperCase()}, прокси ${пркс.toUpperCase()}.`
      + ' Для антиспама это выглядит неестественно и повышает риск ограничения.',
  }
}
