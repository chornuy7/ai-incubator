/**
 * §9: «дожим» — что делать, когда по человеку цель уже закрыта, а он написал снова.
 *
 * Штатно терминальный статус (`target` — цель достигнута, `closed` — отказался) значит
 * «диалог окончен, больше не пишем». Правило верное: без него бот донимал бы людей,
 * которые уже всё сказали. Но у него есть слепое пятно — человек, который написал САМ.
 * Это не наша навязчивость, это входящий интерес, и молчать в ответ глупо.
 *
 * Поэтому: пришло новое входящее в закрытый диалог → отвечаем, но с отдельным
 * счётчиком и жёстким потолком. Исчерпали — замолкаем окончательно.
 */

/** Статусы, на которых штатный диалог считается законченным. */
export const TERMINAL = new Set(['target', 'closed'])

/**
 * Нужно ли включать дожим для этого лида.
 *
 * @param {{status?:string}|null} lead лид из CRM
 * @param {{followUp?:{enabled?:boolean, limit?:number}}|null} agentOrGoal агент (SPEC §1.2); цель — legacy
 * @param {number} already сколько сообщений дожима уже отправлено этому человеку
 * @param {boolean} hasIncoming есть ли НОВОЕ входящее от него
 *
 * SPEC §1.2: дожим настраивается у АГЕНТА, а не у цели (решение звонка 22.07) —
 * «дожимать или отпускать» это манера общения, а не измеримый результат. Второй
 * параметр остался структурно тем же (объект с полем `followUp`), поэтому вызывающий
 * передаёт агента; для целей, созданных до разделения, поле ещё читается — старые
 * данные не ломаем, миграция не нужна.
 * @returns {{ mode:'skip'|'follow-up'|'normal', reason?:string, left?:number }}
 *   `skip` — молчим · `follow-up` — дожимаем · `normal` — обычный диалог
 */
export function followUpDecision(lead, agentOrGoal, already = 0, hasIncoming = true) {
  const status = lead?.status || 'cold'
  if (!TERMINAL.has(status)) return { mode: 'normal' }

  const fu = agentOrGoal?.followUp
  if (!fu?.enabled) {
    return {
      mode: 'skip',
      reason: status === 'closed'
        ? 'отказался — больше не пишем (стоп-лист)'
        : 'выполнил целевое действие — диалог завершён',
    }
  }
  // Дожим — это ОТВЕТ на инициативу человека, а не новая рассылка. Без входящего молчим:
  // иначе «дожим» превратился бы в догоняющие сообщения тому, кто уже всё решил.
  if (!hasIncoming) return { mode: 'skip', reason: 'диалог завершён, новых сообщений нет' }

  const limit = Math.max(1, Number(fu.limit) || 10)
  if (already >= limit) {
    return { mode: 'skip', reason: `дожим исчерпан (${already}/${limit}) — больше не пишем` }
  }
  return { mode: 'follow-up', left: limit - already }
}

/**
 * Указания модели на время дожима. Тон здесь другой, чем в основном диалоге:
 * человек уже прошёл воронку, повторно продавать ему то же самое — верный способ
 * получить блокировку.
 * @param {{followUp?:{instructions?:string}}|null} agentOrGoal агент (SPEC §1.2); цель — legacy
 * @param {string} status терминальный статус лида
 * @param {number} left сколько сообщений дожима осталось
 */
export function followUpPrompt(agentOrGoal, status, left) {
  const lines = [
    '',
    '--- Режим дожима ---',
    status === 'closed'
      ? 'Этот человек РАНЬШЕ ОТКАЗАЛСЯ, но написал сам. Не дави и не уговаривай: ответь на то, что он спросил, и предложи помощь только если он сам к этому ведёт.'
      : 'Этот человек УЖЕ выполнил целевое действие, но написал сам. Не продавай повторно и не повторяй прошлые предложения: ответь по существу и поддержи разговор.',
    `Осталось сообщений в этом режиме: ${left}. Пиши коротко и по делу.`,
  ]
  const extra = String(agentOrGoal?.followUp?.instructions || '').trim()
  if (extra) lines.push(`Указания от владельца кампании: ${extra}`)
  return lines.join('\n')
}

/**
 * Новый статус лида по итогам дожима.
 *
 * Обычная воронка ходит только вперёд, и это правильно: иначе случайное «ок» откатывало бы
 * достигнутую цель. Но дожим — отдельный разговор, и его исход надо зафиксировать:
 * отказался — `closed` (даже если раньше был `target`), снова заинтересовался —
 * возвращаем в работу, чтобы им занялись как живым лидом.
 *
 * @param {string} current текущий (терминальный) статус
 * @param {string} verdict что классификатор увидел в ответе человека
 * @returns {string|null} новый статус или null, если менять нечего
 */
export function followUpStatus(current, verdict) {
  if (verdict === 'closed') return current === 'closed' ? null : 'closed'
  // Ожил после отказа — это снова рабочий лид, а не закрытый.
  if (current === 'closed' && ['hot', 'interested', 'warm'].includes(verdict)) return verdict
  // Цель уже достигнута: заново её «достигать» не нужно, статус не трогаем.
  return null
}
