/**
 * Витрина оплат: ключи строк обязаны быть РАЗНЫМИ.
 *
 * Находка 27.08 (владелец не мог открыть админку). `readAudit` отдаёт время строкой ISO,
 * а в buildRows стояло `Number(e.ts) || 0` — для строки это NaN, то есть НОЛЬ. Отсюда
 * сразу две поломки:
 *   • все покупки планов получали время 0 — в витрине 1970 год;
 *   • и одинаковый ключ `p:0:<человек>`. У кого больше одной оплаченной подписки (на
 *     боевой таких девять), в один upsert прилетали строки с одним ключом, и Postgres
 *     отвечал 21000 «ON CONFLICT DO UPDATE command cannot affect row a second time».
 *
 * Падала не строка — падала пересборка витрины целиком, а с ней вся админ-статистика.
 * Форма цен при этом рисовала нули поверх настоящих цен, и рядом стояла кнопка
 * «Сохранить»: одно нажатие обнулило бы прайс на проде.
 */
import test from 'node:test'
import assert from 'node:assert/strict'
import fs from 'node:fs/promises'

const src = await fs.readFile(new URL('../payments.js', import.meta.url), 'utf8')
const code = src.replace(/^\s*\/\/.*$/gm, '').replace(/\/\*[\s\S]*?\*\//g, '')

test('время события аудита разбирается как ДАТА, а не как число', () => {
  // Date.parse ДОЛЖЕН стоять первым. `Number(e.ts)` рядом допустим как запасной путь
  // для файлового режима, где время лежит числом, — но не вместо разбора ISO.
  assert.ok(/const ts = Date\.parse\(e\.ts\)/.test(code), [
    'readAudit отдаёт ISO-строку. Number("2026-08-11T12:17:39Z") — это NaN,',
    'а значит время 0 и одинаковый ключ у всех покупок одного человека.',
  ].join('\n'))
})

test('ключ покупки плана не строится из одного лишь времени', () => {
  assert.ok(!/id:\s*`p:\$\{ts\}:\$\{uid\}`/.test(code), [
    'Время повторяется, а у события аудита есть собственный уникальный id.',
    'Ключ из времени и человека склеивает две разные оплаты в одну строку.',
  ].join('\n'))
  assert.ok(/e\.id != null/.test(code), 'ключ обязан опираться на собственный id события')
})

test('одинаковые ключи схлопываются до записи, а не роняют витрину', () => {
  assert.ok(/function dedupeById/.test(code), 'нужна страховка от совпавших ключей в одной пачке')
  const at = code.indexOf('function dedupeById')
  const body = code.slice(at, at + 500)
  assert.ok(/console\.warn/.test(body), [
    'Молча схлопывать нельзя: если ключи снова совпадут, об этом надо узнать из лога,',
    'а не искать потом причину расхождения в отчёте по деньгам.',
  ].join('\n'))
  assert.ok(/return dedupeById\(out\)/.test(code), 'buildRows обязан прогонять результат через страховку')
})

test('витрина собирается через buildRows один раз, а не по разным правилам', () => {
  // Правило «что считать доходом» не должно зависеть от того, где лежит витрина:
  // и Supabase, и локальный SQLite получают ОДИН и тот же набор строк.
  const at = code.indexOf('async function doSync')
  const body = code.slice(at, at + 400)
  assert.ok(/await buildRows\(\)/.test(body), 'обе ветки хранения обязаны брать строки из buildRows')
})
