/**
 * MR-260: в шапке панели нет кнопки «Парсинг данных».
 *
 * Владелец 01.09: «парсинг данных скрыть кнопку». Она была рекламной врезкой в рабочей
 * шапке: вела туда же, куда пункт меню слева, но занимала место рядом с числами, за
 * которыми в шапку и приходят — аккаунты в строю, токены, счёт.
 *
 * Тест сторожит именно это: кнопку легко вернуть «заодно», правя соседний блок шапки.
 * При этом сам раздел парсинга обязан остаться доступным из меню — убрать кнопку и убрать
 * функцию это разные вещи, и вторая была бы поломкой.
 */
import test from 'node:test'
import assert from 'node:assert/strict'
import fs from 'node:fs'

const читать = (p) => fs.readFileSync(new URL(p, import.meta.url), 'utf8')

/**
 * Код без комментариев: в них кнопка упоминается как объяснение, почему её больше нет.
 * Заменяем пробелами, а не выбрасываем, — чтобы номера строк оставались настоящими.
 */
function безКомментариев(src) {
  const пробелы = (t) => t.replace(/[^\n]/g, ' ')
  return src.replace(/\{?\/\*[\s\S]*?\*\/\}?/g, пробелы).replace(/\/\/[^\n]*/g, пробелы)
}

test('кнопки «Парсинг данных» в шапке нет', () => {
  const код = безКомментариев(читать('../../src/widgets/AppHeader.tsx'))
  assert.doesNotMatch(код, /Парсинг данных/, 'кнопка вернулась в шапку')
  assert.doesNotMatch(код, /panel\/modules\/parsing/, 'в шапке снова ссылка на парсинг')
  // Иконка была только у этой кнопки: осталась в импорте — значит правку сделали наполовину.
  assert.doesNotMatch(код, /\bRadar\b/, 'неиспользуемый импорт Radar')
})

test('сам раздел парсинга остался — убрана кнопка, а не функция', () => {
  // Убрать кнопку и убрать доступ к парсерам — разные вещи; вторая была бы поломкой.
  const routes = читать('../../src/shared/config/routes.ts')
  for (const путь of ['/panel/modules/parsing', '/panel/modules/parsing-groups', '/panel/modules/parsing-users']) {
    assert.ok(routes.includes(путь), `в меню пропал ${путь}`)
  }
  const app = читать('../../src/App.tsx')
  assert.match(app, /panel\/modules\/:moduleKey/, 'маршрут модулей должен остаться рабочим')
})
