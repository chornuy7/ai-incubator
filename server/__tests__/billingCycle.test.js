/**
 * Цикл подписки — календарный месяц от дня оформления (владелец 31.08).
 *
 * «Списання раз в місяць і в той день, коли саме у нас було оформленна підписка, а не
 * рівно 30 днів. Повинно бути 12 циклів».
 *
 * Здесь считается ЧИСТАЯ арифметика дат, без базы: ошибка в ней стоит денег клиента и
 * проявляется не сразу, а через полгода сползания.
 */
import test from 'node:test'
import assert from 'node:assert/strict'
import { nextCycle, cycleMomentIn, daysInMonth } from '../lib/billingCycle.js'

const дата = (ms) => new Date(ms).toISOString().slice(0, 10)
const utc = (y, m, d) => Date.UTC(y, m - 1, d)

test('за год ровно 12 списаний, и все в одно число', () => {
  /*
   * На 30 сутках было 12 циклов за 360 дней: дата сползала назад на пять дней в год, а раз
   * в шесть лет с человека списывали тринадцатый раз за календарный год.
   */
  let срок = utc(2026, 1, 14)
  const даты = []
  for (let i = 0; i < 12; i++) {
    срок = nextCycle(срок, 14)
    даты.push(дата(срок))
  }
  assert.equal(даты.length, 12)
  assert.equal(даты[11], '2027-01-14', 'через 12 циклов — то же число ровно через год')
  assert.ok(даты.every((d) => d.endsWith('-14')), `все списания 14-го числа, а вышло: ${даты.join(' ')}`)
})

test('короткий февраль: списываем 28-го, но день оплаты остаётся 31-м', () => {
  /*
   * Главная ловушка. Если следующий цикл считать от ФАКТИЧЕСКОЙ даты списания (28 февраля),
   * подписка навсегда переезжает на 28 число: марта, апреля и так далее. День оплаты
   * поэтому берётся с подписки, а не из даты прошлого списания.
   */
  const февраль = nextCycle(utc(2026, 1, 31), 31)
  assert.equal(дата(февраль), '2026-02-28', '31 февраля не существует — списываем в последний день')

  const март = nextCycle(февраль, 31)
  assert.equal(дата(март), '2026-03-31', 'после февраля возвращаемся на 31-е, а не остаёмся на 28-м')

  const апрель = nextCycle(март, 31)
  assert.equal(дата(апрель), '2026-04-30', 'в апреле 30 дней — снова последний день месяца')

  const май = nextCycle(апрель, 31)
  assert.equal(дата(май), '2026-05-31', 'и снова 31-е: день оплаты никуда не уехал')
})

test('високосный год добавляет 29 февраля', () => {
  assert.equal(daysInMonth(2028, 1), 29, '2028 — високосный')
  assert.equal(дата(nextCycle(utc(2028, 1, 30), 30)), '2028-02-29', 'списываем 29-го, а не 28-го')
})

test('время суток сохраняется', () => {
  /*
   * Подписка, оплаченная в 23:50, не должна на следующем цикле истекать в полночь и на
   * десять минут оставлять человека без модулей.
   */
  const оплата = Date.UTC(2026, 4, 10, 23, 50, 0)
  const следующий = new Date(nextCycle(оплата, 10))
  assert.equal(следующий.getUTCHours(), 23)
  assert.equal(следующий.getUTCMinutes(), 50)
})

test('переход через декабрь не теряет год', () => {
  assert.equal(дата(nextCycle(utc(2026, 12, 5), 5)), '2027-01-05')
})

test('момент цикла в текущем месяце — по числу оплаты, с поправкой на длину месяца', () => {
  // По нему решается «сегодня уже пора начислять или ещё рано».
  assert.equal(дата(cycleMomentIn(utc(2026, 2, 15), 31)), '2026-02-28', 'в феврале 31-го не бывает')
  assert.equal(дата(cycleMomentIn(utc(2026, 3, 1), 14)), '2026-03-14')
  assert.ok(utc(2026, 3, 10) < cycleMomentIn(utc(2026, 3, 10), 14), '10-го числа начислять 14-го ещё рано')
  assert.ok(utc(2026, 3, 14) >= cycleMomentIn(utc(2026, 3, 14), 14), '14-го — уже пора')
})
