/**
 * MR-290: в колонку времени нельзя положить число.
 *
 * Проверка появилась после того, как один и тот же промах нашёлся в трёх местах подряд —
 * и все три пережили полный зелёный прогон.
 *
 * Устроен он так. Миграция `2026-09-02-mr290-time-types.sql` перевела 26 колонок из
 * `bigint` в `timestamptz`. В сторах конвертацию довели до мапперов строк и на этом
 * успокоились. Но патчи собираются не только мапперами: в автоматизации, в обращениях и
 * в кэше парсера есть объекты, написанные литералами прямо в месте вызова. Туда
 * по-прежнему клали `Date.now()`.
 *
 * Postgres читает `1787588909052` как дату и ОТКАЗЫВАЕТ. Не «сохранит приблизительно», не
 * «запишет 1970 год» — отказывает. То есть «сохранить правило автоматизации», «отметить
 * обращение прочитанным» и «включить слежение за запросом» ломались бы насовсем, а не на
 * время выката. Обычные тесты этого не видят: они гоняют файловый режим, где те же поля
 * остаются числом и всё сходится.
 *
 * ЧТО ЭТА ПРОВЕРКА ЛОВИТ И ЧЕГО НЕ ЛОВИТ — честно, потому что от этого зависит, можно ли
 * на неё полагаться.
 *
 *   Ловит: колонку времени, которую файл использует ТОЛЬКО с сырым значением, ни разу не
 *   переведя. Ровно так выглядел промах в `automation/store.js`: рядом стояли пять
 *   переведённых полей и две забытых строки.
 *
 *   НЕ ловит: файл, где колонка где-то переводится, а в одном месте нет — так было в
 *   `tickets.js`. Отличить это статически нельзя, поэтому там сделано иначе: перевод
 *   уехал внутрь `dbPatch`, и забыть его стало негде (см. `timesToDb` и тесты на неё в
 *   `dbTime.test.js`). Здесь остаётся более грубая, но бесшумная сеть — а бесшумность тут
 *   и есть условие полезности: проверка с ложными срабатываниями будет заглушена в первый
 *   же день и перестанет ловить что бы то ни было.
 */
import { test } from 'node:test'
import assert from 'node:assert/strict'
import fs from 'node:fs/promises'

const MIGRATION = new URL('../../supabase/migrations/2026-09-02-mr290-time-types.sql', import.meta.url)
const SERVER = new URL('../', import.meta.url)

/** Формы, в которых значение времени уже готово к записи. */
const ПЕРЕВЕДЕНО = ['toDbTime(', 'iso(', 'nowIso', 'new Date(', 'now()']

/**
 * Таблица → её колонки времени. Читается из самой миграции, а не переписывается списком.
 *
 * Привязка к ТАБЛИЦЕ, а не просто к имени колонки, здесь принципиальна: `created_at` и
 * `updated_at` есть у половины таблиц базы, и проверка «по имени» ругалась бы на
 * `module_actions.created_at` и `subscriptions.updated_at`, которые никуда не переезжали.
 * Три ложных срабатывания — и проверку заглушают.
 */
async function времяПоТаблицам() {
  const sql = await fs.readFile(MIGRATION, 'utf8')
  const блок = sql.slice(sql.indexOf('spec text[][] := array['), sql.indexOf('];'))
  const карта = new Map()
  const добавить = (t, c) => карта.set(t, (карта.get(t) || new Set()).add(c))
  for (const m of блок.matchAll(/\['([a-z_]+)',\s*'([a-z_]+)',/g)) добавить(m[1], m[2])
  // Время, заведённое сразу правильным, — тот же случай и та же цена ошибки.
  добавить('parser_cache', 'last_run_at')
  добавить('parser_cache', 'next_run_at')
  добавить('campaign_schedules', 'run_at')
  добавить('campaign_schedules', 'last_run_at')
  добавить('channels', 'last_post_at')
  добавить('channels', 'last_stats_at')
  assert.ok(карта.size > 10, `таблиц разобрано подозрительно мало: ${карта.size}`)
  return карта
}

/** Файлы сервера, кроме тестов, разовых скриптов и данных. */
async function файлыСервера(dir = SERVER, out = []) {
  for (const e of await fs.readdir(dir, { withFileTypes: true })) {
    if (['__tests__', 'scripts', 'data', 'node_modules'].includes(e.name)) continue
    const u = new URL(e.name + (e.isDirectory() ? '/' : ''), dir)
    if (e.isDirectory()) await файлыСервера(u, out)
    else if (e.name.endsWith('.js')) out.push(u)
  }
  return out
}

test('колонку времени нигде не заполняют ТОЛЬКО сырым значением', async () => {
  const карта = await времяПоТаблицам()
  const плохие = []

  for (const файл of await файлыСервера()) {
    const код = await fs.readFile(файл, 'utf8')
    const имя = decodeURIComponent(файл.pathname.split('/server/')[1])
    if (!/\.(insert|upsert|update)\(/.test(код)) continue
    // Какие таблицы трогает этот файл — по обращениям `from('…')`.
    const свои = new Set([...код.matchAll(/from\('([a-z_]+)'\)/g)].map((m) => m[1]))

    for (const [таблица, колонки] of карта) {
      if (!свои.has(таблица)) continue
      for (const колонка of колонки) {
        const места = [...код.matchAll(new RegExp(`\\b${колонка}\\s*:\\s*([^,\\n]+)`, 'g'))].map((m) => m[1].trim())
        if (!места.length) continue
        if (места.some((v) => ПЕРЕВЕДЕНО.some((f) => v.includes(f)))) continue
        плохие.push(`${имя} → ${таблица}.${колонка}: ни одного перевода, например «${места[0]}»`)
      }
    }
  }

  assert.deepEqual(плохие, [], [
    'Колонка времени заполняется сырым значением и НИ РАЗУ не переводится в этом файле.',
    'Postgres читает epoch-мс как дату и откажет — действие сломается совсем,',
    'а не «сохранится приблизительно». Файловый режим при этом остаётся зелёным.',
    ...плохие.map((x) => '  · ' + x),
  ].join('\n'))
})
