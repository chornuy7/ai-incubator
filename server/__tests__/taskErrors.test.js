/**
 * Что видит оператор, когда задача упала.
 *
 * Владелец увидел на дашборде «fromRow is not a function or its return value is not
 * iterable» и написал: «это бред какой-то, такой ошибки не может быть». Он прав дважды.
 * Во-первых, за ней стоял настоящий дефект (перепутанный контракт стора). Во-вторых —
 * и это отдельная проблема — фрагмент внутренней поломки вообще не должен попадать на
 * экран человека, который просто запустил задачу: сделать с такой строкой он ничего не
 * может, а выглядит она как претензия к его настройкам.
 *
 * Разделение не эвристическое: встроенные типы ошибок JavaScript бросает сам движок, и
 * условием работы они не бывают никогда.
 */
import test from 'node:test'
import assert from 'node:assert/strict'
import { taskErrorText } from '../lib/taskErrors.js'

test('дефект кода не показывается оператору дословно', () => {
  // Ровно та ошибка, что была на дашборде.
  const текст = taskErrorText(new TypeError('fromRow is not a function or its return value is not iterable'))
  assert.ok(!/fromRow/.test(текст), 'внутренности наружу не идут')
  assert.ok(!/is not a function/.test(текст), 'текст движка наружу не идёт')
  assert.match(текст, /на нашей стороне/i, 'человеку сказано, что это не его вина')
  assert.match(текст, /заново/i, 'сказано, что делать дальше')
})

test('все встроенные типы ошибок считаются дефектом, а не ситуацией', () => {
  for (const Тип of [TypeError, ReferenceError, RangeError, SyntaxError, URIError]) {
    const текст = taskErrorText(new Тип('внутренняя деталь'))
    assert.ok(!текст.includes('внутренняя деталь'), `${Тип.name}: подробности утекли наружу`)
  }
})

test('наша ошибка — это условие работы, её показываем как есть', () => {
  /*
   * «Нет сессии», «прокси не отвечает», «не хватает монет» — по таким сообщениям оператор
   * и чинит. Спрятать их за общей фразой значит отобрать у него единственную подсказку.
   */
  for (const сообщение of [
    'Нет сессии — нужна переавторизация',
    'Прокси px_1 назначен аккаунту, но в каталоге его нет',
    'Не хватает монет для запуска',
  ]) {
    assert.equal(taskErrorText(new Error(сообщение)), сообщение)
  }
})

test('не Error и пустое сообщение не дают пустую строку на экране', () => {
  // Пустая «ошибка» в карточке задачи читается как «всё в порядке, но красное».
  assert.equal(taskErrorText(null), 'Ошибка')
  assert.equal(taskErrorText('строка вместо ошибки'), 'Ошибка')
  assert.equal(taskErrorText(new Error('')), 'Ошибка')
})

test('воркеры не пишут в лог задачи сырой текст исключения', async () => {
  /*
   * Сторож на весь класс: одно место, где снова напишут `err.message` прямо в лог задачи,
   * вернёт на дашборд стектрейс. Проверяем оба воркера, где это уже случалось.
   */
  const fs = await import('node:fs/promises')
  for (const файл of ['../modules/workers.js', '../neuroCommenting/worker.js']) {
    const код = await fs.readFile(new URL(файл, import.meta.url), 'utf8')
    const сырые = код.split('\n').filter((l) => /appendLog\([^)]*'error'[^)]*err instanceof Error \? err\.message/.test(l))
    assert.deepEqual(сырые, [], `${файл}: текст исключения уходит в лог задачи напрямую — нужен taskErrorText`)
  }
})
