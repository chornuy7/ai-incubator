/**
 * MR-228: отмена подписки.
 *
 * Заказчик 30.08: «У тебя должно быть написано, какая подписка оплачена, до какого числа,
 * что в неё входит, и кнопка отмены. Возвратов нет».
 *
 * Отмена НЕ отбирает доступ: период оплачен, человек дорабатывает его до конца. Отменяется
 * только следующее списание — и вместе с ним следующее начисление токенов, иначе платформа
 * выдавала бы топливо за неоплаченный месяц.
 *
 * Проверять живым прогоном нечем: продление и начисление в файловом режиме сразу возвращают
 * пусто, а на боевой базе это чужие деньги. Поэтому здесь закрыты решения, которые в деньгах
 * стоят дорого и которые легко «упростить» не подумав.
 */
import test from 'node:test'
import assert from 'node:assert/strict'
import fs from 'node:fs/promises'

const читать = (p) => fs.readFile(new URL(p, import.meta.url), 'utf8')
/** Только исполняемые строки: комментарии не должны подтверждать сами себя. */
const код = async (p) => {
  const строки = (await читать(p)).split(/\r?\n/)
  return строки.filter((s) => !/^\s*(\/\/|\*|\/\*)/.test(s)).join('\n')
}

test('отменённую подписку не продлевают и не заряжают токенами', async () => {
  /*
   * Две шкалы, и обе должны видеть отмену. Забудут в начислении — человек, отменивший
   * подписку, будет вечно получать месячную порцию токенов бесплатно; забудут в списании —
   * с него продолжат брать деньги после отмены. Второе хуже.
   */
  for (const [файл, что] of [['../subscriptionBilling.js', 'списание денег'], ['../tokenCredit.js', 'начисление токенов']]) {
    const src = await код(файл)
    assert.ok(/canceled_at/.test(src), `${что}: отмена не учитывается вовсе`)
    assert.ok(/if \(r\.canceled_at\) return false/.test(src), `${что}: отменённая подписка должна отсеиваться при отборе`)
    assert.ok(/select\([^)]*canceled_at/.test(src), `${что}: колонку отмены забыли вытянуть запросом — признак всегда будет пустым`)
  }
})

test('отмена не трогает ни срок, ни состав подписки', async () => {
  /*
   * Соблазн «отменить» удалением строки или обнулением expires_at. Тогда доступ пропадёт в
   * ту же секунду — а он оплачен, и возврата мы не делаем. Получилось бы, что человек
   * заплатил за месяц, отменил на второй день и остался без всего.
   */
  const src = await код('../index.js')
  const at = src.indexOf("app.post('/api/subscription/cancel'")
  assert.ok(at > 0, 'маршрут отмены не найден')
  const тело = src.slice(at, at + 2200)

  assert.ok(/canceled_at:/.test(тело), 'отмена ставит отметку времени')
  assert.ok(!/expires_at/.test(тело), 'срок при отмене двигать нельзя — период оплачен')
  assert.ok(!/\.delete\(\)/.test(тело), 'удалять подписку нельзя: потеряются и дата конца, и состав')
  assert.ok(!/changeUsd|changeCoins/.test(тело), 'возврата денег нет — отмена не двигает баланс')
})

test('чужую подписку отменить нельзя', async () => {
  // Это деньги конкретного человека: без проверки любой сотрудник отменил бы подписку владельца.
  const src = await код('../index.js')
  const at = src.indexOf("app.post('/api/subscription/cancel'")
  const тело = src.slice(at, at + 2200)
  assert.ok(/isAdminRequest/.test(тело), 'нужна проверка админа для чужой подписки')
  assert.ok(/403/.test(тело), 'чужая подписка без прав администратора — отказ')
})

test('оплата снимает отметку отмены', async () => {
  /*
   * Иначе отменивший и передумавший платит впустую: деньги списались, срок сдвинулся, а
   * следующего продления всё равно нет. Снимать надо ЛЮБОЙ оплатой, а не только докупкой
   * модулей: продление тем же набором — то же самое «я остаюсь».
   */
  const src = await код('../index.js')
  assert.ok(/canceled_at: null/.test(src), 'после оплаты отметка отмены должна сниматься')
  const at = src.indexOf('canceled_at: null')
  const выше = src.slice(Math.max(0, at - 2500), at)
  assert.ok(!/if \(addedModules\.length\)\s*\{[^}]*$/.test(выше),
    'снятие отметки не должно сидеть внутри ветки «добавили модули» — продление набора туда не попадает')
})

test('панель знает про отмену: признак приходит с балансом', async () => {
  // Без этого кнопка «Отменить подписку» осталась бы видимой после отмены, а человек
  // нажимал бы её второй раз и не понимал, сработало ли.
  const src = await код('../index.js')
  assert.ok(/canceledAt/.test(src), 'сервер должен отдавать признак отмены в балансе')
  const тип = await читать('../../src/api/balanceApi.ts')
  assert.ok(/canceledAt\?: number \| null/.test(тип), 'в типе баланса на клиенте нужен признак отмены')
})

test('в шапке подписки видно, что оплачено, до какого числа и что входит', async () => {
  /*
   * Дословно из задачи: «должно быть написано, какая подписка оплачена, до какого числа,
   * что в неё входит, и кнопка отмены». Всё четыре — на одном экране.
   */
  const стр = await код('../../src/pages/SubscriptionPage.tsx')
  assert.ok(/Подписка «\$\{имяНабора\}»/.test(стр), 'название подписки в шапке')
  assert.ok(/оплачено до \$\{exp\.date\}/.test(стр), 'дата окончания в шапке')
  assert.ok(/что входит/.test(стр), 'состав подписки должен раскрываться в шапке')
  assert.ok(/Отменить подписку/.test(стр), 'кнопка отмены в шапке')
  assert.ok(/Возврата за оплаченный период нет/.test(стр), 'подтверждение обязано сказать про отсутствие возврата')
})

test('кнопка отмены красная сразу, а не по наведению', async () => {
  /*
   * Заказчик 31.08: «має бути червоною по стандарту, а не коли наводиш». Разрушающее
   * действие должно читаться как разрушающее ДО того, как на него навели мышь — иначе
   * серую кнопку нажимают, не задумавшись. Так же оформлены «Закрыть» в тикетах и
   * «Удалить» в автопостинге.
   */
  const стр = await код('../../src/pages/SubscriptionPage.tsx')
  const строки = стр.split(/\r?\n/)
  const строка = строки.find((l) => /Отменить подписку/.test(l) && /className/.test(l))
    || строки.find((l) => /btn-ghost/.test(l) && /rose/.test(l))
  assert.ok(строка, 'не нашёл разметку кнопки отмены')
  assert.ok(/text-rose-300/.test(строка), 'кнопка отмены должна быть красной в обычном состоянии')
  assert.ok(!/text-muted hover:text-rose/.test(строка), 'красный только по наведению — так нельзя')
})

test('слово «Подписка» в шапке не повторяется дважды', async () => {
  /*
   * Было «Подписка «14 модулей» Подписка бессрочная»: имя набора и статус писали это слово
   * каждый сам. И счёт модулей стоял в кавычках, будто набор так и называется — кавычки
   * уместны только вокруг настоящего имени.
   */
  const стр = await код('../../src/pages/SubscriptionPage.tsx')
  assert.ok(!/'Подписка бессрочная'/.test(стр), 'статус не должен повторять слово «Подписка»')
  assert.ok(!/`Подписка истекла/.test(стр), 'статус не должен повторять слово «Подписка»')
  assert.ok(/Подписка · \$\{состав\.length\}/.test(стр), 'без имени набора счёт модулей пишется без кавычек')
})

test('после отмены кнопка отмены пропадает', async () => {
  const стр = await код('../../src/pages/SubscriptionPage.tsx')
  assert.ok(/!отменена && \(/.test(стр), 'кнопка отмены не должна показываться уже отменённой подписке')
  assert.ok(/отменена \? .*доступ до/.test(стр) || /доступ до \$\{exp\.date\}/.test(стр),
    'отменённая подписка обязана показывать, до какого числа доступ ещё есть')
})

test('колонка отмены заведена миграцией', async () => {
  const sql = await читать('../../supabase/migrations/2026-08-31-subscription-cancel.sql')
  assert.ok(/add column if not exists canceled_at/.test(sql), 'колонка добавляется идемпотентно')
  assert.ok(!/drop |delete /i.test(sql), 'миграция отмены ничего не удаляет')
})

