/**
 * Ежемесячное продление подписки со списанием денег (решение владельца 28.08).
 *
 * «Робимо списання кожного місяця, якщо річна підписка то просто нараховуємо токени.
 * Якщо балансу не вистачає тоді закриваємо доступ».
 *
 * До этого деньги снимались один раз — при покупке, сразу за весь период; автопродления
 * не было вовсе (нашли прогоном MR-193).
 *
 * Поведение проверяется живым прогоном на базе (scripts/check-renewal.mjs) — функции
 * продления в файловом режиме сразу возвращают пусто. Здесь закрыта дорога назад по
 * решениям, которые в деньгах стоят дорого и которые легко «упростить» не подумав.
 */
import test from 'node:test'
import assert from 'node:assert/strict'
import fs from 'node:fs/promises'

const src = await fs.readFile(new URL('../subscriptionBilling.js', import.meta.url), 'utf8')
const index = await fs.readFile(new URL('../index.js', import.meta.url), 'utf8')
const fn = (() => {
  const at = src.indexOf('export async function renewDueSubscriptions')
  assert.ok(at > 0, 'renewDueSubscriptions не найден')
  return src.slice(at)
})()

test('деньги списываются ДО сдвига срока, а не после', () => {
  // Наоборот было бы хуже: срок сдвинули, а списание не прошло — человек пользуется
  // платформой бесплатно, и заметить это можно только по отчёту в конце месяца.
  const charge = fn.indexOf('changeUsd(-cost')
  const extend = fn.indexOf("update({ expires_at: iso")
  assert.ok(charge > 0 && extend > 0, 'не найдены списание и сдвиг срока')
  assert.ok(charge < extend, 'списание должно идти раньше сдвига срока')
})

test('не хватило денег — не списываем ничего и срок не двигаем', () => {
  const at = fn.indexOf('if (usd < cost)')
  assert.ok(at > 0, 'проверка достаточности баланса не найдена')
  // Берём РОВНО тело ветки — до выхода из итерации. Иначе в срез попадает списание,
  // которое стоит сразу после блока и к нехватке денег отношения не имеет.
  const end = fn.indexOf('continue', at) + 'continue'.length
  assert.ok(end > at, 'ветка нехватки денег должна выходить из итерации')
  const branch = fn.slice(at, end)
  assert.ok(/continue/.test(branch), 'при нехватке денег подписка должна пропускаться целиком')
  assert.ok(!/changeUsd/.test(branch), 'частичное списание недопустимо: снять «сколько есть» нельзя')
  assert.ok(/console\.warn/.test(branch), 'молчаливое закрытие доступа выглядит как поломка — нужен след в логе')
})

test('повторное списание в том же месяце невозможно', () => {
  // Списание и сдвиг срока — две записи, между ними процесс может умереть. Если
  // полагаться только на срок, следующий тик снимет деньги второй раз за тот же месяц.
  assert.ok(/last_charge_month === month/.test(src), 'отметка месяца обязана проверяться при отборе')
  assert.ok(/last_charge_month: month/.test(fn), 'отметка месяца обязана ставиться вместе со сдвигом срока')
})

test('годовую подписку продление не трогает', () => {
  // У годовой срок далеко впереди — она просто не попадает в окно продления.
  assert.ok(/RENEW_BEFORE_MS/.test(src) && /RENEW_AFTER_MS/.test(src), 'окно продления должно быть явным')
  assert.ok(/exp <= nowMs \+ RENEW_BEFORE_MS/.test(src), 'продлеваем только те, чей срок подходит')
})

test('брошенную подписку сами не воскрешаем', () => {
  // Иначе подписка, брошенная полгода назад, однажды сама спишет деньги с пополненного
  // кошелька — человек об этом даже не вспомнит.
  assert.ok(/exp >= nowMs - RENEW_AFTER_MS/.test(src), 'нужен предел, как давно мог кончиться срок')
})

test('срок считается от прежнего окончания, а не от «сейчас»', () => {
  // Тик ходит раз в шесть часов и приходит с опозданием. Считать от «сейчас» — значит
  // каждый месяц отъедать у человека несколько оплаченных часов.
  assert.ok(/Math\.max\(sub\.expiresAt/.test(fn), 'новый срок обязан отсчитываться от прежнего')
})

test('продление идёт раньше начисления токенов', () => {
  // Иначе подписка, у которой срок кончился сегодня, будет отброшена начислением как
  // истёкшая: человек заплатил, а топливо получит только в следующем месяце.
  const renew = index.indexOf('renewDueSubscriptions()')
  const credit = index.indexOf('creditDueTokens()')
  assert.ok(renew > 0 && credit > 0, 'обе задачи должны быть в тике')
  assert.ok(renew < credit, 'продление обязано идти первым')
})

test('цена продления считается тем же кодом, что и цена покупки', () => {
  // Вопрос владельца 28.08: «взял подписку на месяц по скидке — следующий месяц по
  // скидке или по полному прайсу?». Ответ: по той же цене. Скидка здесь — свойство
  // НАБОРА (сетап или собранный админом пакет), а не разовая акция: человек не менял
  // состав, значит и счёт меняться не должен.
  //
  // Простая сумма по monthMap этого не знает: клиент, купивший «Парсер + Комментинг»
  // за $20, на продлении получил бы счёт по полному прайсу. Ровно это и было в первой
  // версии продления — нашли по вопросу владельца, до выката.
  assert.ok(/subscriptionCost\(/.test(fn), 'цена продления обязана считаться через subscriptionCost — тем же кодом, что и покупка')
  assert.ok(/listBundles\(\)/.test(src), 'наборы админа нужны, иначе их цена не найдётся')
  assert.ok(/listSetups\(\)/.test(src), 'сетапы нужны, иначе скидка набора потеряется')
  assert.ok(!/const cost = sub\.modules\.reduce/.test(fn), 'простая сумма по прайсу здесь недопустима: она не знает про скидки')
})

test('о списании за продление человека уведомляют', async () => {
  /*
   * Правка заказчика 30.08, увидел на прогоне: «чого немає повідомлення про подовження
   * підписки?». Колокольчик отсеивал ВСЕ отрицательные суммы и всё, что не «пополнение».
   * Подписка теперь продлевается сама и сама снимает деньги — молчать об этом нельзя:
   * человек узнаёт о списании из выписки банка, а об отключённых модулях — наткнувшись
   * на закрытый модуль.
   */
  const fs = await import('node:fs/promises')
  const src = await fs.readFile(new URL('../../src/widgets/AppHeader.tsx', import.meta.url), 'utf8')
  const at = src.indexOf('for (const w of wallet)')
  assert.ok(at > 0, 'разбор кошелька не найден')
  const блок = src.slice(at, at + 2400)

  assert.ok(!/if \(w\.amount <= 0/.test(блок), [
    'Отсев всех отрицательных сумм отрезал ровно то, о чём важнее всего сказать:',
    'списание за автоматическое продление подписки.',
  ].join('\n'))
  assert.ok(/продлени/i.test(блок), 'списание за продление должно попадать в уведомления')
  assert.ok(/токены подписки/i.test(блок), 'месячное начисление токенов — тоже событие для человека')

  const хвост = src.slice(at, at + 3600)
  assert.ok(/if \(срок\.expired &&/.test(хвост), [
    'Не хватило денег — подписка не продлевается, модули отключаются.',
    'Строки в кошельке при этом НЕТ (списания не было), поэтому смотреть надо на срок.',
  ].join('\n'))
  assert.ok(/'Подписка не продлена'/.test(хвост), 'человеку надо сказать прямо: подписка не продлена')
  assert.ok(/модули отключены/.test(хвост), 'и что именно из-за этого перестало работать')
  assert.ok(/sub-expired/.test(хвост), 'у уведомления об истёкшей подписке должен быть свой ключ')
})
