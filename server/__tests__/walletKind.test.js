/**
 * MR-230: классификатор «операция по подписке» прибит к формулировкам сервера.
 *
 * В окне «История операций» на странице подписок должны быть только подписки и купленные
 * модули. Отличить их можно лишь по тексту причины: поле `kind` в журнале занято другим
 * смыслом (покупка или выдача — для учёта дохода), отдельной колонки нет.
 *
 * Текстовый разбор ломается молча: поменяли слово в причине — и история у клиента
 * опустела, а никто не заметил. Поэтому тест берёт формулировки ИЗ КОДА СЕРВЕРА и
 * проверяет, что классификатор их узнаёт.
 */
import test from 'node:test'
import assert from 'node:assert/strict'
import fs from 'node:fs/promises'

const читать = (p) => fs.readFile(new URL(p, import.meta.url), 'utf8')

/** Простое повторение классификатора: тест не должен зависеть от сборки фронта. */
const ПРЕФИКСЫ = ['Подписка', 'Продление подписки', 'Токены подписки', 'Подарочные токены']
const подписочная = (r) => ПРЕФИКСЫ.some((p) => String(r || '').trim().startsWith(p))

test('список префиксов в классификаторе совпадает с этим тестом', async () => {
  const src = await читать('../../src/features/billing/walletKind.ts')
  for (const p of ПРЕФИКСЫ) {
    assert.ok(src.includes(`'${p}'`), `префикс «${p}» пропал из классификатора`)
  }
})

test('все причины, которые сервер пишет по подписке, узнаются', async () => {
  /*
   * Собираем строки причин прямо из кода: где пишется операция кошелька, там и текст.
   * Если формулировку поменяют, а классификатор нет — этот тест упадёт.
   */
  const файлы = ['../index.js', '../subscriptionBilling.js', '../tokenCredit.js']
  const причины = []
  for (const f of файлы) {
    const src = await читать(f)
    for (const m of src.matchAll(/change(?:Coins|Usd)\([^,]+,\s*`([^`]+)`/g)) причины.push(m[1])
  }
  assert.ok(причины.length >= 6, `ожидали найти причины операций в коде, нашли ${причины.length}`)

  const подписочные = причины.filter((r) => /подписк|Подарочные токены/i.test(r))
  assert.ok(подписочные.length >= 4, `подписочных причин найдено ${подписочные.length}: ${подписочные.join(' | ')}`)
  for (const r of подписочные) {
    // Подставляем что-нибудь вместо ${…}, текст от этого не меняется.
    const текст = r.replace(/\$\{[^}]+\}/g, 'X')
    assert.ok(подписочная(текст), [
      `Причина «${текст}» пишется сервером как операция по подписке, но классификатор её не узнаёт.`,
      'История на странице подписок покажет неполный список — и никто этого не заметит.',
    ].join('\n'))
  }
})

test('чужие операции в историю подписок не попадают', () => {
  for (const r of ['parsing: 1 действ.', 'Пополнение $ из админ-панели', 'Покупка токенов: 63.574 ⚡', 'Куплено за $6.99']) {
    assert.equal(подписочная(r), false, `«${r}» не относится к подписке — ей место в кошельке`)
  }
})

/** Файл БЕЗ комментариев — иначе проверка ловит собственные пояснения. */
async function код(путь) {
  const src = await читать(путь)
  return src.split('\n').filter((l) => {
    const t = l.trim()
    return t && !t.startsWith('//') && !t.startsWith('*') && !t.startsWith('/*') && !t.startsWith('{/*')
  }).join('\n')
}

test('история не обрезает текст и разнесена на две строки', async () => {
  /*
   * Заказчик 30.08 дословно: «Вы не должны обрезать никогда текст. С какого месяца по какой —
   * должен быть полностью прописан». И отдельно: «до-после на первой строке, а снизу дата».
   */
  const профиль = await код('../../src/pages/ProfilePage.tsx')
  const строкаПричины = профиль.split('\n').find((l) => l.includes('{r.reason ||'))
  assert.ok(строкаПричины, 'строка с причиной операции не найдена')
  assert.ok(!/truncate/.test(строкаПричины), 'причина операции обрезалась многоточием — так нельзя')
  assert.ok(/break-words/.test(строкаПричины), 'длинная причина должна переноситься')

  const статистика = await код('../../src/pages/StatisticsPage.tsx')
  const вСтатистике = статистика.split('\n').find((l) => l.includes('{r.reason}'))
  assert.ok(вСтатистике && !/truncate/.test(вСтатистике), 'в кошельке статистики причина тоже не обрезается')
})

test('в истории есть фильтр по валюте — и в подписках, и в статистике', async () => {
  for (const [файл, где] of [['../../src/pages/ProfilePage.tsx', 'история'], ['../../src/pages/StatisticsPage.tsx', 'статистика']]) {
    const src = await код(файл)
    assert.ok(/'coins', 'Токены'/.test(src) && /'usd', 'Деньги'/.test(src), `${где}: нужен переключатель «токены / деньги»`)
  }
})

test('окно на странице подписок показывает только подписку', async () => {
  const профиль = await код('../../src/pages/ProfilePage.tsx')
  assert.ok(/только="subscription"/.test(профиль), 'модалка со страницы подписок обязана сужать список')
  assert.ok(/isSubscriptionEntry/.test(профиль), 'сужение идёт через общий классификатор, а не через свой разбор текста')
  assert.ok(/Покупок подписки и модулей пока не было/.test(профиль), [
    'Пустой список в окне подписок и в кошельке значит разное.',
    'Сказать «операций не было», когда они есть, но не про подписку, — враньё.',
  ].join('\n'))
})

test('изменение баланса подписано и читается', async () => {
  /*
   * Заказчик 30.08, глядя на «10111.00 → 11511.00»: «тут не дуже подається, як зміна
   * балансу йде». Два голых числа без подписи и без единицы: непонятно ни что это остаток,
   * ни в чём он — токены или доллары.
   */
  const utils = await код('../../src/shared/lib/utils.ts')
  assert.ok(/export function balance/.test(utils), 'нужен отдельный формат для остатка')
  // Без \\B пробел встанет и перед трёхзначным числом: « 160».
  assert.ok(utils.includes('\\B(?=(\\d{3})+'), 'разряды в остатке разделяются — 10 111, а не 10111')

  const профиль = await код('../../src/pages/ProfilePage.tsx')
  assert.ok(профиль.includes('>остаток</span>'), 'числа остатка подписаны словом — иначе это просто два числа')
  assert.ok(/fmtBalance\(r\.before\)/.test(профиль) && /fmtBalance\(r\.after\)/.test(профиль), 'остаток печатается читаемым форматом')
  assert.ok(!/fmtCoins\(r\.before\)/.test(профиль), 'старый формат с «.00» и без разрядов не должен остаться')

  const статистика = await код('../../src/pages/StatisticsPage.tsx')
  assert.ok(/fmtBalance\(r\.after\)/.test(статистика), 'в кошельке статистики остаток печатается тем же форматом')
})

test('набор в истории называется своим именем, а не списком модулей', async () => {
  /*
   * Заказчик 30.08: «ми брали підписку все включено, а чого тут так багато — можна написати
   * "Продление подписки (месяц) Всё включено", і так само з токенами».
   *
   * Раньше каждая операция перечисляла модули: «Мейлинг, Нейрокомментинг, Нейрочаттинг и
   * ещё 11». Человек покупал НАБОР и своей покупки в этой строке не узнавал.
   */
  const { describeModules, listModules, bundleName } = await import('../lib/subscriptionLabel.js')

  /*
   * Подкладываем свой файл наборов: без него в файловом режиме наборов нет вовсе, и
   * проверка «нашёлся ли набор по составу» ничего не проверяет — она проходит даже если
   * поиск вырезать целиком.
   */
  const os = await import('node:os')
  const path = await import('node:path')
  const fsp = await import('node:fs/promises')
  const каталог = await fsp.mkdtemp(path.join(os.tmpdir(), 'bundles-'))
  const файл = path.join(каталог, 'bundles.json')
  await fsp.writeFile(файл, JSON.stringify([{ id: 'b1', name: 'Мой набор', modules: ['mailing', 'warming'], price: 10 }]))
  const было = process.env.BUNDLES_FILE
  process.env.BUNDLES_FILE = файл
  try {
    assert.equal(await bundleName(['warming', 'mailing']), 'Мой набор', 'состав совпал — пишем имя набора, порядок не важен')
    assert.equal(await describeModules(['warming', 'mailing']), 'Мой набор', 'подпись операции берёт имя набора')
    assert.equal(await bundleName(['mailing']), null, 'частичное совпадение набором не считается')
  } finally {
    if (было === undefined) delete process.env.BUNDLES_FILE
    else process.env.BUNDLES_FILE = было
    await fsp.rm(каталог, { recursive: true, force: true })
  }
  assert.equal(await describeModules(['mailing', 'warming']), listModules(['mailing', 'warming']),
    'не совпало с набором — остаётся прежнее перечисление')
  assert.equal(await describeModules([]), '', 'пустой состав не даёт подписи')

  const много = ['a', 'b', 'c', 'd', 'e']
  assert.match(listModules(много), /и ещё 2$/, 'длинный список по-прежнему сворачивается')
})

test('подпись операции считается в одном месте', async () => {
  /*
   * Три места пишут операции по подписке: покупка, продление, начисление токенов. Если
   * каждое соберёт подпись по-своему, в истории у одного человека набор будет называться
   * по-разному в соседних строках.
   */
  for (const f of ['../index.js', '../subscriptionBilling.js', '../tokenCredit.js']) {
    const src = await код(f)
    assert.ok(/describeModules\(/.test(src), `${f}: подпись должна идти через общий describeModules`)
  }
  const billing = await код('../subscriptionBilling.js')
  assert.ok(!/names\.slice\(0, 3\)/.test(billing), 'своя сборка перечисления в биллинге не нужна — она в общем месте')

  // Панель берёт имя набора ОТТУДА ЖЕ, с сервера, а не сверяет состав второй раз.
  const шапка = await код('../../src/widgets/AppHeader.tsx')
  assert.ok(/balance\?\.setName/.test(шапка), 'кошелёк показывает имя набора, посчитанное сервером')
  assert.ok(!/listSetups|listBundles/.test(шапка), 'вторая проверка состава на клиенте однажды разъедется с серверной')
})
