/**
 * MR-290: цепочка миграций должна ссылаться только на то, что к этому моменту существует.
 *
 * Проверка появилась не из головы. При сдаче MR-290 я разобрал 608 ссылок между
 * миграциями и нашёл две, которые ведут в никуда: `2026-07-30-owner-and-types.sql`
 * правит таблицу `parsed_channels`, а `2026-07-31-rls.sql` — `api_keys`. Ни одна
 * миграция этих таблиц не создаёт, и в базе их нет: проверено запросом, обе отвечают
 * «relation does not exist».
 *
 * Почему это важно и почему при этом ничего не сломано СЕЙЧАС. Прод наполняли руками
 * через SQL Editor, и прогонятор миграций подружен с ним через `--baseline`: файлы
 * отмечены применёнными, не выполняясь. То есть цепочка с нуля не проигрывается — и не
 * должна, об этом прямо написано в шапке `server/scripts/migrate.mjs`. Пока живёт одна
 * база, дыра незаметна.
 *
 * Заметна она станет в тот день, когда понадобится ВТОРАЯ база: стенд, новый регион,
 * разбор аварии на копии. Тогда прогон упадёт на пятом файле, и разбираться в этом
 * придётся в худший для этого момент.
 *
 * Исправить те две ссылки правкой файлов НЕЛЬЗЯ: они уже применены, а прогонятор считает
 * контрольные суммы и останавливается на изменённом файле — и правильно делает.
 * Поэтому они внесены сюда списком известных долгов, а тест сторожит, чтобы НОВЫХ таких
 * ссылок не появлялось.
 */
import { test } from 'node:test'
import assert from 'node:assert/strict'
import fs from 'node:fs/promises'

const MIGRATIONS = new URL('../../supabase/migrations/', import.meta.url)
const SCHEMA = new URL('../../supabase/schema.sql', import.meta.url)

/**
 * Известные долги — ссылки на таблицы, которых не создаёт ни одна миграция.
 * Список закрытый: новая строка здесь означает новый долг и должна обсуждаться в ревью,
 * а не добавляться заодно с правкой.
 */
const ИЗВЕСТНЫЕ_ДОЛГИ = new Set(['parsed_channels', 'api_keys'])

/** Слова, которые грубый разбор принимает за имена таблиц: `on delete cascade`, `update set`. */
const НЕ_ТАБЛИЦЫ = new Set(['public', 'select', 'values', 'conflict', 'only', 'table', 'if', 'set', 'of', 'cascade', 'null'])

/** Убрать комментарии: закомментированный `create table` таблицы не создаёт. */
const безКомментариев = (sql) => sql.split(/\r?\n/).filter((l) => !/^\s*--/.test(l)).join('\n').toLowerCase()

test('миграции не ссылаются на объекты, которых к этому моменту нет', async () => {
  const files = (await fs.readdir(MIGRATIONS)).filter((f) => f.endsWith('.sql')).sort()
  const позиция = new Map(files.map((f, i) => [f, i]))

  // Что уже стоит на проде — по снимку схемы в репозитории. Это и есть честная точка
  // отсчёта: прогонятор заводится на живой базе через --baseline, а не с нуля.
  const снимок = безКомментариев(await fs.readFile(SCHEMA, 'utf8'))
  const существует = new Map()
  for (const m of снимок.matchAll(/create table (?:if not exists )?([a-z_][a-z0-9_]*)/g)) {
    if (!существует.has(m[1])) существует.set(m[1], '(снимок схемы)')
  }

  const рано = []
  const вникуда = []

  for (const f of files) {
    const sql = безКомментариев(await fs.readFile(new URL(f, MIGRATIONS), 'utf8'))

    // Ссылки проверяем ДО регистрации создаваемого в этом же файле: внутри одного файла
    // порядок строк уже проверен самим применением, а нас интересует порядок МЕЖДУ файлами.
    const ссылки = new Set()
    for (const re of [
      /references\s+([a-z_][a-z0-9_]*)\s*\(/g,
      /alter table (?:if exists )?(?:public\.)?([a-z_][a-z0-9_]*)/g,
      /\bon ([a-z_][a-z0-9_]*)\s*\(/g,
      /insert into\s+([a-z_][a-z0-9_]*)/g,
    ]) for (const m of sql.matchAll(re)) ссылки.add(m[1])

    const своё = new Set([...sql.matchAll(/create table (?:if not exists )?([a-z_][a-z0-9_]*)/g)].map((m) => m[1]))

    for (const объект of ссылки) {
      if (НЕ_ТАБЛИЦЫ.has(объект) || своё.has(объект)) continue
      const источник = существует.get(объект)
      if (!источник) {
        if (!ИЗВЕСТНЫЕ_ДОЛГИ.has(объект)) вникуда.push(`${f} → ${объект}`)
        continue
      }
      if (источник !== '(снимок схемы)' && позиция.get(источник) > позиция.get(f)) {
        рано.push(`${f} → ${объект} (создаётся позже, в ${источник})`)
      }
    }

    for (const t of своё) if (!существует.has(t)) существует.set(t, f)
  }

  assert.deepEqual(рано, [], [
    'Миграция обращается к объекту, который создаётся ПОЗЖЕ по алфавиту.',
    'Файлы применяются по именам, поэтому на чистой базе такой прогон упадёт:',
    ...рано.map((x) => '  · ' + x),
  ].join('\n'))

  assert.deepEqual(вникуда, [], [
    'Миграция обращается к таблице, которую не создаёт ни одна миграция и которой нет в снимке схемы.',
    'На чистой базе прогон здесь упадёт. Если объект и правда нужен — заведите его миграцией;',
    'если это долг из прошлого — обсудите и внесите в ИЗВЕСТНЫЕ_ДОЛГИ явно:',
    ...вникуда.map((x) => '  · ' + x),
  ].join('\n'))
})

test('список известных долгов не растёт молча', async () => {
  // Тест выше пропускает только то, что перечислено здесь. Если список начнёт пополняться
  // «заодно», проверка превратится в формальность — поэтому его размер зафиксирован.
  assert.equal(ИЗВЕСТНЫЕ_ДОЛГИ.size, 2,
    'Долгов стало больше или меньше. Больше — обсудите, почему завели новую висячую ссылку. ' +
    'Меньше — уберите лишнее из списка и уменьшите число здесь.')
  assert.ok(ИЗВЕСТНЫЕ_ДОЛГИ.has('parsed_channels') && ИЗВЕСТНЫЕ_ДОЛГИ.has('api_keys'),
    'состав долгов изменился — проверьте, что старые действительно закрыты')
})
