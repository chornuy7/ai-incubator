test('нехватка колонки не выдаётся за отсутствие таблицы', () => {
  /*
   * Поймано живьём на этой же задаче: добавили `author_id`, база его ещё не знала —
   * сохранение шаблона провалилось, а роут ответил `ok: true`. Шаблон исчез без следа.
   *
   * PostgREST пишет «schema cache» и про таблицу, и про колонку, а прежнее правило ловило
   * оба случая одним куском. Вызывающий код на «таблицы нет» молчит и идёт дальше — и
   * молчал он на потерянной записи.
   */
  const src = читать('../modulePresets.js')
  const at = src.indexOf('const isMissingTable')
  assert.ok(at > 0, 'проверка не найдена')
  const тело = src.slice(at, src.indexOf('\n}', at))
  assert.ok(/column/i.test(тело), 'нехватка колонки должна распознаваться отдельно')
  assert.ok(/return false/.test(тело), 'на нехватку колонки ответ — «это не отсутствующая таблица»')
  assert.ok(!/\/module_presets\|schema cache\|does not exist/.test(тело),
    'широкое правило «что угодно про schema cache» проглатывает потерю данных')
})

test('шаблон сохраняется вместе с автором, а не рядом с ним', () => {
  // Колонки в базе перечислены поимённо: поле, забытое в маппере, теряется молча —
  // объект наружу вернётся правильный, а в базу уедет без автора.
  const src = читать('../modulePresets.js')
  assert.ok(/author_id: p\.authorId/.test(src), 'автор должен попадать в строку базы')
  assert.ok(/r\.author_id \? \{ authorId: r\.author_id \}/.test(src), 'автор должен читаться обратно')
  const sql = читать('../../supabase/migrations/2026-09-01-preset-author.sql')
  assert.ok(/add column if not exists author_id/.test(sql), 'колонка заводится миграцией идемпотентно')
  assert.ok(!/update .*module_presets.*set author_id/i.test(sql),
    'проставлять автора задним числом нельзя: у шаблона сотрудника автором стал бы владелец пространства')
})

test('база без новой колонки не роняет сохранение и не молчит', () => {
  /*
   * Миграции доезжают до базы отдельно от кода, и между выкатами колонки может не быть.
   * Ронять сохранение нельзя — человек потеряет собранные настройки; молчать тоже нельзя —
   * именно молчание съело шаблон при проверке этой задачи.
   *
   * Тот же приём уже применён в журнале кошелька (appendWalletEntry).
   */
  const src = читать('../modulePresets.js')
  const at = src.indexOf('async function upsertPresets')
  assert.ok(at > 0, 'не нашёл запись шаблонов')
  const тело = src.slice(at, src.indexOf('\n}\n', at))
  assert.ok(/could not find the '\(\[\^'\]\+\)' column/i.test(тело), 'имя незнакомой колонки должно вытаскиваться из ответа базы')
  assert.ok(/console\.warn/.test(тело), 'о деградации надо говорить в лог, иначе потеря поля пройдёт незамеченной')
  assert.ok(/глубина < 5/.test(тело), 'повтор по ответу базы должен быть ограничен')
  assert.ok(/throw new Error/.test(тело), 'любая другая ошибка базы обязана всплыть, а не пропасть')
})

test('клиенту не показывают текст ошибки базы', () => {
  // «Could not find the 'author_id' column of 'module_presets' in the schema cache» — это
  // сообщение для разработчика: чужой язык и внутренности схемы. Наружу — по-человечески.
  const src = код('../modules/routes.js')
  const at = src.indexOf("modulesRouter.post('/:moduleKey/presets'")
  const тело = src.slice(at, src.indexOf('modulesRouter.delete', at))
  assert.ok(!/err\.message/.test(тело), 'текст ошибки базы наружу отдавать нельзя')
  assert.ok(/console\.error/.test(тело), 'настоящая причина должна попадать в лог')
  assert.ok(/Не удалось сохранить шаблон/.test(тело), 'человек должен получить понятное сообщение')
})
