/**
 * MR-185/MR-176: чужой шаблон не должен уносить личные промпты человека.
 *
 * Находка 27.08 (проверка владельца на тестовом аккаунте). Шаблон — общий набор
 * рабочего пространства, и применяется он к ЗАПУСКУ, а не к личным промптам: применил
 * шаблон администратора — на экране его тексты, но в базе у тебя по-прежнему свои.
 * Так и было задумано, и так оно и работает.
 *
 * А вот дальше был тихий провал. «Сохранить» в карточке отправляло на сервер ВЕСЬ
 * набор с экрана. То есть: применил чужой шаблон → поправил одну карточку → нажал
 * сохранить → остальные ПЯТЬ чужих текстов уехали к тебе как твои собственные, поверх
 * твоих. Человек правил одну карточку и не догадывался, что потерял пять своих.
 *
 * Ни один тест этого не ловил: в файловом режиме и в обычном сценарии (без шаблона)
 * набор с экрана совпадает с сохранённым, и разницы не видно.
 */
import test from 'node:test'
import assert from 'node:assert/strict'
import fs from 'node:fs/promises'

const SRC = new URL('../../src/', import.meta.url)
const read = (p) => fs.readFile(new URL(p, SRC), 'utf8')
/** Комментарии не считаем: в них про старое поведение как раз и написано. */
const code = (s) => s.replace(/^\s*\/\/.*$/gm, '').replace(/\/\*[\s\S]*?\*\//g, '')

test('карточка сохраняет СЕБЯ, а не весь набор с экрана', async () => {
  const src = code(await read('features/modules/shared/PromptCards.tsx'))
  const at = src.indexOf('const saveEdit')
  assert.ok(at > 0, 'обработчик сохранения карточки не найден')
  const body = src.slice(at, src.indexOf('}', src.indexOf('closeModal()', at)))
  assert.ok(/onSaveCard\(\s*modalIndex\s*,/.test(body), [
    'Сохранение должно отдавать наружу НОМЕР карточки и её текст.',
    'Если отдавать весь массив bodies, то после применения чужого шаблона правка одной',
    'карточки запишет человеку остальные пять чужих текстов поверх его собственных.',
  ].join('\n'))
  assert.ok(!/\[\s*\.\.\.\s*bodies\s*\]/.test(body),
    'набор с экрана (bodies) не должен становиться тем, что уезжает на сервер')
})

test('применение шаблона не пишет промпты на сервер', async () => {
  const src = code(await read('features/modules/shared/promptDefaults.ts'))
  const at = src.indexOf('const replace =')
  assert.ok(at > 0, 'подстановка набора из шаблона не найдена')
  const body = src.slice(at, at + 200)
  assert.ok(!/saveUserPrompts/.test(body), [
    'Шаблон применяют к ЗАПУСКУ, а не к личным промптам человека.',
    'Запись на сервер здесь означала бы, что чужой шаблон переписал чьи-то промпты.',
  ].join('\n'))
})

test('сохранение карточки берёт соседние из сохранённого, а не с экрана', async () => {
  const src = code(await read('features/modules/shared/promptDefaults.ts'))
  const at = src.indexOf('const saveCard =')
  assert.ok(at > 0, 'saveCard не найден — набор целиком сохранять больше нельзя')
  const body = src.slice(at, src.indexOf('const replace', at))
  assert.ok(/storedRef\.current\[/.test(body), [
    'Соседние карточки обязаны браться из того, что реально сохранено за человеком.',
    'Иначе тексты применённого чужого шаблона уедут в базу как его собственные.',
  ].join('\n'))
  assert.ok(/i === index/.test(body), 'меняться должна ровно одна карточка')
  // Набор с экрана читать здесь нельзя ВООБЩЕ: после применения шаблона там чужие
  // тексты. Текущее состояние меняется через setBodies(prev => ...), где `bodies` не
  // участвует, — значит его упоминание тут уже само по себе ошибка.
  assert.ok(!/\bbodies\s*[.[]/.test(body), [
    'saveCard не должен читать набор с экрана (bodies): это и есть та самая утечка —',
    'чужой шаблон на экране уезжает в базу как личные промпты человека.',
  ].join('\n'))
})

test('у хука промптов нет способа записать весь набор разом', async () => {
  const src = code(await read('features/modules/shared/promptDefaults.ts'))
  const ret = src.slice(src.indexOf('return { bodies'))
  assert.ok(!/\bsave\b\s*[,}]/.test(ret), [
    'Наружу не должно торчать «сохранить всё»: единственный законный повод записать',
    'промпт — человек отредактировал КОНКРЕТНУЮ карточку.',
  ].join('\n'))
})

test('удаление шаблона спрашивает подтверждение', async () => {
  // Шаблоны — общий набор рабочего пространства. Крестик стоит вплотную к самому
  // шаблону, и одного промаха хватало, чтобы чужая настройка исчезла у всех без следа.
  const src = code(await read('features/modules/shared/PresetBar.tsx'))
  const at = src.indexOf('onDelete && (')
  assert.ok(at > 0, 'кнопка удаления шаблона не найдена')
  const body = src.slice(at, src.indexOf('</button>', at))
  // MR-197: спрашиваем НАШЕЙ модалкой. Требование то же — подтверждение обязательно, —
  // но браузерное окно не показывает, что именно удаляют, и не различает опасные действия.
  assert.ok(/confirmDialog/.test(body), 'удаление общего шаблона обязано спрашивать подтверждение')
  assert.ok(!/window\.confirm/.test(body), 'подтверждение спрашивает наша модалка, а не браузерное окно')
  assert.ok(/p\.name/.test(body), 'в вопросе должно быть НАЗВАНИЕ шаблона — иначе непонятно, что именно удаляют')
})
