/**
 * MR-194: клиенту не показываем цену ОДНОГО токена в пакете.
 *
 * Созвон 27.08. Под каждым пакетом в окне кошелька выводилось «0.140 $ / ⚡». Цифра
 * честная — владелец это признал, «там абсолютно всё справедливо написано», — но она
 * позволяет сравнить пакеты между собой и увидеть, где выгода меньше: 6.99/50 = 0.140,
 * а 21.99/200 = 0.110. Дословно: «а то мы тогда будем проёбываться… мы просто показываем,
 * а что там человек купит — это уже его дело».
 *
 * Тест текстовый, потому что защищает решение, а не поведение: строку легко вернуть
 * обратно, «чтобы было понятнее», и никто этого не заметит до следующего созвона.
 */
import test from 'node:test'
import assert from 'node:assert/strict'
import fs from 'node:fs/promises'

const SRC = new URL('../../src/', import.meta.url)
const read = (p) => fs.readFile(new URL(p, SRC), 'utf8')
/** Код без комментариев: расчёт в комментарии оставлен намеренно и нарушением не является. */
const code = (s) => s.replace(/^\s*\/\/.*$/gm, '').replace(/\/\*[\s\S]*?\*\//g, '').replace(/\{\s*\/\*[\s\S]*?\*\/\s*\}/g, '')

test('цена одного токена в пакете клиенту не выводится', async () => {
  const src = await read('widgets/AppHeader.tsx')
  const live = code(src)
  assert.ok(!/p\.price\s*\/\s*p\.coins/.test(live), [
    'В окне кошелька снова считается цена за токен (p.price / p.coins).',
    'Владелец просил её скрыть: она показывает, на каком пакете наша выгода меньше.',
    'Если строка нужна для отладки — оставляйте её закомментированной, как сейчас.',
  ].join('\n'))
})

test('расчёт оставлен закомментированным, а не вырезан', async () => {
  // Владелец сказал дословно: «не удалить, а закомментировать» — цифра справедливая
  // и ещё понадобится. Если её вырезать совсем, при следующем разговоре придётся
  // восстанавливать по памяти, почему там было именно p.price / p.coins.
  const src = await read('widgets/AppHeader.tsx')
  assert.ok(/p\.price\s*\/\s*p\.coins/.test(src), 'расчёт цены за токен должен остаться в комментарии')
})

test('в админке цена за токен и себестоимость остаются', async () => {
  // Скрываем только у клиента. Внутри цифра нужна: по ней решают, какую цену ставить.
  const admin = await read('pages/AdminStatsPage.tsx')
  assert.ok(/токен/i.test(admin), 'в разделе цен админки расчёт по токенам должен быть виден')
})
