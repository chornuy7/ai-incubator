/**
 * MR-203: выход стирает следы уходящего человека из браузера.
 *
 * Созвон 27.08, увидели живьём: на экране мелькнули 80 ⚡, и только через две секунды
 * пришли настоящие 200 ⚡. Разбор заказчика: выход отправляет запрос на бэкенд и на этом
 * заканчивается — «для сервера ты разлогинен, но для фронта всё ещё остались данные
 * предыдущего пользователя». Дословное требование: «система должна удалить все данные,
 * весь кэш и все абсолютно данные, связанные с предыдущим пользователем».
 *
 * Выход и раньше делал жёсткую перезагрузку — она чистит память приложения. Проблема в
 * том, что перезагрузку ПЕРЕЖИВАЕТ: кэш состава подписки, закрытые уведомления, аватар,
 * черновики вкладки, куки.
 *
 * Тест текстовый: поведение проверяется сценарием в браузере, а здесь закрыта дорога
 * назад — чтобы чистку не убрали «за ненадобностью» и чтобы не начали заодно стирать
 * настройки устройства или ключи чужой зоны.
 */
import test from 'node:test'
import assert from 'node:assert/strict'
import fs from 'node:fs/promises'

const src = await fs.readFile(new URL('../../src/features/auth/session.ts', import.meta.url), 'utf8')
const body = (name) => {
  const at = src.indexOf(name)
  assert.ok(at > 0, `${name} не найден`)
  return src.slice(at, at + 2200)
}

test('выход зовёт чистку следов, а не только снимает токен', () => {
  const logout = src.slice(src.indexOf('logout: () => {'), src.indexOf('logout: () => {') + 900)
  assert.ok(/clearUserTraces\(/.test(logout), [
    'Выход обязан чистить следы уходящего человека.',
    'Снять токен и перезагрузить страницу недостаточно: кэш подписки, закрытые',
    'уведомления, аватар, черновики вкладки и куки перезагрузку переживают.',
  ].join('\n'))
  assert.ok(/clearUserTraces\(uid/.test(logout), 'чистке нужен id уходящего: именные ключи без него не вычислить')
})

test('чистятся хранилище, черновики вкладки и куки', () => {
  const fn = body('export function clearUserTraces')
  assert.ok(/localStorage\.removeItem/.test(fn), 'ключи localStorage должны сниматься')
  assert.ok(/sessionStorage\.clear\(\)/.test(fn), 'черновики вкладки уходят вместе с человеком')
  assert.ok(/document\.cookie/.test(fn), 'куки перезагрузка не трогает — их надо чистить явно')
})

test('настройки устройства выход не сбрасывает', () => {
  // Тема и язык к человеку не относятся: это настройка браузера. Сбрасывать их на
  // выходе — значит каждый раз возвращать светлую тему тому, кто выбрал тёмную.
  const fn = body('const DEVICE_PREFS')
  assert.ok(/ai-incubator:v3/.test(fn), 'язык и тема должны переживать выход')
  assert.ok(/nav-collapsed/.test(fn), 'свёрнутые группы меню — тоже настройка устройства')
  const clear = body('export function clearUserTraces')
  assert.ok(/keep\.has\(key\)/.test(clear), 'список сохраняемого обязан проверяться при чистке')
})

test('выход из одной зоны не выкидывает из другой', () => {
  // Панель и админка живут раздельно (созвон 19.08): один и тот же человек может быть
  // залогинен в обеих, и выход из панели не должен закрывать админку.
  const fn = body('const OTHER_ZONE_KEYS')
  assert.ok(/ADMIN_SESSION_KEY/.test(fn) && /PANEL_SESSION_KEY/.test(fn), 'ключи обеих зон должны учитываться')
  const clear = body('export function clearUserTraces')
  assert.ok(/OTHER_ZONE_KEYS\(zone\)/.test(clear), 'ключи чужой зоны обязаны попадать в сохраняемые')
})

test('чужие именные ключи на общем компьютере не трогаем', () => {
  // На одном компьютере могут работать двое. Стирать ключи, принадлежащие ДРУГОМУ
  // человеку, мы не вправе — уходит один, а настройки потеряет и второй.
  const fn = body('export function clearUserTraces')
  assert.ok(/named\[1\] !== userId/.test(fn), 'именной ключ чужого пользователя должен пропускаться')
})

test('чистятся и наши ключи без общего префикса', () => {
  // Ручная проверка заказчика 29.08: после выхода в хранилище остались `lowbal:hide`,
  // `neuro-dialogs:goal` и безымянный `notif-dismissed` — цель диалогов уходящего и
  // список закрытых им уведомлений. Чистка шла по одному префиксу `ai-incubator:`, а
  // эти ключи писались (и пишутся) без него.
  const fn = body('const OUR_PREFIXES')
  assert.ok(/'lowbal:'/.test(fn), '«больше не показывать поп-ап баланса» — выбор конкретного человека')
  assert.ok(/'neuro-dialogs:'/.test(fn), 'цель и режим нейродиалогов остались от прежних версий и лежат в живых браузерах')
  assert.ok(/'notif-dismissed'/.test(fn), 'безымянный список закрытых уведомлений — данные прошлого человека')
  const clear = body('export function clearUserTraces')
  assert.ok(/isOurs\(key\)/.test(clear), 'чистка обязана идти по всем нашим пространствам, а не по одному префиксу')
})

test('чужие ключи расширений браузера не трогаем', () => {
  // Рядом в том же хранилище лежат `loglevel` и `__coupert_perf_last_report` — это
  // браузерные расширения человека. «Стереть всё» сломало бы ему их настройки.
  const fn = body('const OUR_PREFIXES')
  assert.ok(!/localStorage\.clear\(\)/.test(src), 'localStorage.clear() снёс бы и чужие ключи — так нельзя')
  assert.ok(/startsWith\(p\)/.test(src.slice(src.indexOf('const isOurs'), src.indexOf('const isOurs') + 300)),
    'наши пространства должны определяться списком, а не «всё, что нашли»')
  assert.ok(fn.includes('['), 'OUR_PREFIXES — перечисление наших префиксов')
})
