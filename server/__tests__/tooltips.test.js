/**
 * Единый вид подсказок на всё приложение.
 *
 * Заказчик 01.09: «зроби щоб всюди підказки були як на 2 скріні» — как тёмная всплывашка
 * `Tip`, а не как плашка браузера. Просьба звучит второй раз: 20.08 под неё сделали
 * компонент `Tip`, но перевести на него успели считаные места.
 *
 * Поэтому сторожим не «переписали ли файлы», а само свойство: нативных подсказок в панели
 * не остаётся, и выглядят они все одинаково.
 */
import test from 'node:test'
import assert from 'node:assert/strict'
import fs from 'node:fs'

const читать = (p) => fs.readFileSync(new URL(p, import.meta.url), 'utf8')

test('подсказки перехватываются глобально и включены при старте', () => {
  const слой = читать('../../src/shared/lib/tooltips.ts')
  assert.ok(/removeAttribute\('title'\)/.test(слой),
    'нативную подсказку надо снимать: иначе браузер покажет свою поверх нашей')
  assert.ok(/setAttribute\('data-tip'/.test(слой), 'текст должен сохраняться, а не теряться вместе с атрибутом')

  const старт = читать('../../src/main.tsx')
  assert.ok(/installTooltips\(\)/.test(старт), 'слой подсказок должен включаться при старте приложения')
})

test('перенос title повторяется на каждом наведении', () => {
  /*
   * React при следующем рендере вернёт `title` на элемент — он есть в разметке. Разовый
   * обход по документу вылечил бы страницу до первого обновления данных, а дальше нативные
   * плашки полезли бы обратно, и вернулись бы они не сразу, а через минуту-другую работы —
   * то есть уже после проверки.
   */
  const слой = читать('../../src/shared/lib/tooltips.ts')
  const at = слой.indexOf('function tipOf')
  assert.ok(at > 0, 'не нашёл чтение подсказки')
  assert.ok(/addEventListener\('pointerover', show/.test(слой), 'подсказка читается по наведению')
  assert.ok(!/querySelectorAll\('\[title\]'\)/.test(слой), 'разовый обход документа не годится: React вернёт title обратно')
})

test('вид общей подсказки совпадает с Tip', () => {
  // Две ветки оформления — это те же разные подсказки, только обе наши.
  const слой = читать('../../src/shared/lib/tooltips.ts')
  const ui = читать('../../src/shared/ui/index.tsx')
  for (const класс of ['border-line', 'bg-surface', 'text-[11px]', 'max-w-[280px]', 'whitespace-pre-line', 'shadow-xl']) {
    assert.ok(слой.includes(класс), `в общем слое нет оформления «${класс}»`)
    assert.ok(ui.includes(класс), `в Tip нет оформления «${класс}» — виды разъехались`)
  }
})

test('подсказка не переживает элемент, к которому относится', () => {
  /*
   * Клик по кнопке-иконке чаще всего открывает окно или уносит строку из списка. Плашка,
   * оставшаяся висеть, поясняет то, чего на экране уже нет.
   */
  const слой = читать('../../src/shared/lib/tooltips.ts')
  for (const [событие, зачем] of [['pointerdown', 'клик'], ['scroll', 'прокрутка'], ['resize', 'смена размера окна']]) {
    assert.ok(new RegExp(`'${событие}'`).test(слой), `${зачем} должна убирать подсказку`)
  }
})

test('кнопка-иконка не немеет для скринридера', () => {
  // Весь смысл такой кнопки был в `title`. Сняв его молча, мы бы его и потеряли.
  const слой = читать('../../src/shared/lib/tooltips.ts')
  assert.ok(/aria-label/.test(слой), 'снятый title должен дублироваться в aria-label')
  assert.ok(/!\(el\.textContent \|\| ''\)\.trim\(\)/.test(слой),
    'подпись добавляем только там, где читать больше нечего: у кнопки с текстом свой текст важнее')
})
