/**
 * MR-235: счётчик аккаунтов в шапке не показывает выдуманный лимит.
 *
 * В шапке было «98 / 50» — сколько аккаунтов есть и лимит тарифа. Заказчик 30.08:
 * «каким образом у меня стало 98 аккаунтов? Это баг, и баг серьёзный».
 *
 * Разбор показал, что подсчёт был верным, а неверным было ВТОРОЕ число: `accountLimit`
 * лежит в server/balance.js как свойство тарифа и НИГДЕ не проверяется — ни при добавлении
 * аккаунта, ни при импорте. 98 при лимите 50 не ошибка: 98 настоящие, а 50 ничего не
 * значат. Заказчик: «нету никакого драного лимита по аккаунтам; там должно быть написано
 * 8 из 10 — сколько работает».
 *
 * Тест текстовый: поведение видно глазами, а здесь закрыта дорога назад — чтобы лимит не
 * вернули в интерфейс как «полезную информацию».
 */
import test from 'node:test'
import assert from 'node:assert/strict'
import fs from 'node:fs/promises'

/**
 * Файл БЕЗ комментариев. Первая версия теста этого не делала и падала на собственных
 * пояснениях: слово `accountLimit` встречалось в комментарии рядом с правкой, и проверка
 * считала, что лимит всё ещё показывается.
 */
async function код(путь) {
  const src = await fs.readFile(new URL(путь, import.meta.url), 'utf8')
  return src
    .split('\n')
    .filter((l) => {
      const t = l.trim()
      return t && !t.startsWith('//') && !t.startsWith('*') && !t.startsWith('/*')
    })
    .join('\n')
}

test('шапка не показывает лимит тарифа', async () => {
  const src = await код('../../src/widgets/AppHeader.tsx')
  assert.ok(!/accountLimit/.test(src), [
    'Лимит аккаунтов нигде не проверяется — показывать его значит обещать несуществующее правило.',
    'В шапке должно быть «сколько в строю из скольких есть».',
  ].join('\n'))
  assert.ok(/рабочихАккаунтов/.test(src) && /всегоАккаунтов/.test(src), 'счётчик считает рабочие и общее число')
  assert.ok(/isBrokenAccount/.test(src), '«в строю» определяется общим предикатом нерабочего аккаунта')
})

test('выбор аккаунтов не показывает лимит тарифа', async () => {
  const src = await код('../../src/features/account-picker/AccountPicker.tsx')
  assert.ok(!/accountLimit/.test(src), 'в пикере тоже стоял выдуманный лимит — «выбрано N из 50»')
  assert.ok(/доступноВыбора/.test(src), 'вместо лимита показываем, сколько аккаунтов доступно для выбора')
})

test('лимит тарифа ни на что не влияет — иначе его надо показывать', async () => {
  // Поле не удаляем: оно приходит с сервера и понадобится, когда лимит действительно
  // введут. Тест фиксирует, что СЕЙЧАС по нему не принимается ни одного решения.
  const balance = await код('../balance.js')
  const решения = balance
    .split('\n')
    .filter((l) => /accountLimit/.test(l) && /\b(if|throw|return\s+\w+\s*[<>])/.test(l))
  assert.deepEqual(решения, [], [
    'По лимиту где-то принимается решение — значит правило появилось.',
    'Тогда его надо показывать человеку и заводить отдельную задачу, а не оставлять молча.',
  ].join('\n'))
})

test('по клику видно, ПОЧЕМУ аккаунты не в строю', async () => {
  /*
   * Ради этого счётчик и нажимают. Заказчик 30.08: «если я туда нажму, я должен увидеть
   * всплывающее окошко, которое мне скажет: у меня из них два аккаунта, Вася и Вова, они
   * в спамблоке».
   *
   * Первая версия правки показывала только пояснительную подсказку («не в строю — мёртвый
   * прокси и статусы, из которых не запустить»). Это объяснение правила, а не ответ на
   * вопрос «какие именно и почему».
   */
  const src = await код('../../src/widgets/AppHeader.tsx')
  assert.ok(/неВСтрою/.test(src), 'нужен разбор нерабочих аккаунтов, а не только общее число')
  assert.ok(/Мёртвый прокси/.test(src) && /Без прокси/.test(src), 'причины по прокси названы отдельно — их чинят в другом разделе')
  assert.ok(/STATUS_META/.test(src), 'остальные причины берутся из общих подписей статусов, а не пишутся заново')
  assert.ok(/setAccOpen/.test(src), 'разбор открывается по клику, а не живёт в подсказке')
  assert.ok(/имена\.slice\(0, 8\)/.test(src), 'аккаунты названы поимённо — «Вася и Вова», а не «2 штуки»')
  // При десяти тысячах аккаунтов «остальные 9992 дохлые» список имён нечитаем — обрезаем.
  assert.ok(/и ещё/.test(src), 'длинный список имён обрезается счётчиком «и ещё N»')
})

test('причина в разборе — ссылка в менеджер с готовым фильтром', async () => {
  /*
   * Доработка MR-235: «зроби щоб були клікабельні — натиснув спамблок, відкрились акки,
   * які в спамблоці». Показать число мало: если из 49 аккаунтов 31 в спамблоке, человек
   * иначе идёт искать их руками в общем списке.
   */
  const шапка = await код('../../src/widgets/AppHeader.tsx')
  assert.ok(/nav\(`\/panel\?\$\{ссылка\}`\)/.test(шапка), 'группа причины ведёт в менеджер с фильтром')
  assert.ok(/risk=deadProxy/.test(шапка) && /risk=noProxy/.test(шапка), 'причины по прокси ведут на фильтр РИСКА')
  assert.ok(/status=\$\{a\.status\}/.test(шапка), 'остальные причины ведут на фильтр СТАТУСА')

  const менеджер = await код('../../src/pages/AccountsPage.tsx')
  assert.ok(/useTabParam<AccountStatus \| 'all'>\('all', 'status'\)/.test(менеджер), 'фильтр статуса читается из адреса')
  assert.ok(/useTabParam<RiskKey \| 'all'>\('all', 'risk'\)/.test(менеджер), 'фильтр риска читается из адреса')
  assert.ok(!/useState<AccountStatus \| 'all'>/.test(менеджер), [
    'Фильтр в локальном состоянии ссылку из шапки не примет:',
    'переход открыл бы общий список, и человек искал бы те самые 31 вручную.',
  ].join('\n'))
})

test('несколько записей в адрес складываются, а не затирают друг друга', async () => {
  /*
   * Регресс, найденный заказчиком сразу после переноса фильтров в адрес: плитки статуса
   * перестали срабатывать — клик по «Активные» писал только ?tab=accounts.
   *
   * Обработчик плитки делает ТРИ записи подряд: статус, риск, вкладка. React Router
   * разрешает `prev` из текущего адреса, поэтому все три стартовали с одной базы и
   * выживала последняя. Пока фильтры жили в состоянии компонента, конфликта не было.
   *
   * Хук общий — на нём же держатся вкладки, поэтому регресс здесь ломает не только
   * менеджер аккаунтов.
   */
  const хук = await код('../../src/shared/lib/useTabParam.ts')
  assert.ok(/буфер/.test(хук), 'записи должны копиться в общем буфере в пределах обработчика')
  assert.ok(/queueMicrotask/.test(хук), 'буфер сбрасывается микрозадачей — следующий обработчик начинает с чистого адреса')
  assert.ok(/const база = буфер \?\? new URLSearchParams\(prev\)/.test(хук), 'база берётся из буфера, если он уже заполнен в этом обработчике')
})
