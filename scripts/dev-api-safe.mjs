/**
 * Локальный бэкенд для разработки — БЕЗ фоновых задач.
 *
 * Зачем отдельный вход. `npm run dev` поднимает обычный сервер, а он вместе с API
 * запускает планировщики: автоматизацию, кроны, пересчёты. Данные у нас общие
 * (DATA_BACKEND=supabase), поэтому вторая копия сервера на машине разработчика начнёт
 * запускать НАСТОЯЩИЕ задачи по правилам клиентов — тратить их аккаунты и деньги.
 *
 * Здесь тот же сервер, но с SCHEDULERS=off: отвечает на запросы, ничего не запускает сам.
 * Ровно то, что нужно, когда правишь интерфейс и хочешь посмотреть его вживую.
 *
 * Запуск: node scripts/dev-api-safe.mjs   (или конфигурация «ai-incubator-api-safe»)
 */
process.env.SCHEDULERS = 'off'

/*
 * Порт API закрепляем ЗДЕСЬ, иначе он уводит порт у фронта.
 *
 * `vite.config.ts` читает `PORT` (порт веб-сервера), а `server/config.js` — цепочку
 * `API_PORT || PORT || 3001`. Пока `PORT` никто не выставляет, всё сходится: фронт на
 * 5173, API на 3001, прокси `/api → localhost:3001` попадает куда надо.
 *
 * Но `npm run dev:safe` поднимает оба процесса ОДНОЙ командой, и запуск через
 * preview-механизм агента (конфигурация `ai-incubator-safe`) выставляет `PORT` на всё
 * дерево процессов. Тогда `PORT` читают оба: vite занимает его под фронт, а API пытается
 * сесть туда же. На 3001 не остаётся никого, каждый запрос `/api/*` упирается в
 * ECONNREFUSED, и vite отдаёт наружу 500 — включая вход в панель.
 *
 * Симптом при этом обманчивый: страница открывается, сервер «работает», а любое действие
 * даёт 500. Искать причину начинают в бэкенде, которого на этом порту просто нет.
 *
 * `??=`, а не присваивание: заданный руками `API_PORT` остаётся главнее.
 */
process.env.API_PORT ??= '3001'

await import('../server/index.js')
