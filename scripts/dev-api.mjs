/**
 * Локальный бэкенд для разработки — обычный, с фоновыми задачами.
 *
 * Отличается от `dev-api-safe.mjs` ровно одним: планировщики НЕ выключены. Нужен, когда
 * проверяешь саму автоматизацию, а не интерфейс. Для правки интерфейса берите безопасный
 * вход — при общих данных вторая копия сервера начнёт запускать настоящие задачи по
 * правилам клиентов.
 *
 * Существует этот файл ради одной строки ниже — закрепления порта.
 *
 * `vite.config.ts` читает `PORT` (порт веб-сервера), а `server/config.js` — цепочку
 * `API_PORT || PORT || 3001`. Пока `PORT` никто не выставляет, всё сходится: фронт на
 * 5173, API на 3001, прокси `/api → localhost:3001` попадает куда надо. Но `npm run dev`
 * поднимает оба процесса ОДНОЙ командой, и запуск через preview-механизм агента
 * выставляет `PORT` на всё дерево процессов. Тогда `PORT` читают оба: vite занимает его
 * под фронт, а API пытается сесть туда же. На 3001 не остаётся никого, каждый запрос
 * `/api/*` упирается в ECONNREFUSED, и vite отдаёт наружу 500 — включая вход в панель.
 *
 * Симптом обманчивый: страница открывается, сервер «работает», а любое действие даёт 500.
 * Причину начинают искать в бэкенде, которого на этом порту просто нет.
 *
 * `??=`, а не присваивание: заданный руками `API_PORT` остаётся главнее.
 */
process.env.API_PORT ??= '3001'

await import('../server/index.js')
